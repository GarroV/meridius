#!/usr/bin/env node
// Печатает порт приложения этой копии — чтобы за ним могла сходить оболочка.
//
// Нужен ровно одному потребителю — `scripts/up`: он пишет адрес продукта в вывод и
// сверяет порты базы, то есть знать порт ему надо ДО запуска. Считать его там заново
// нельзя: своя копия разбора в `up` и была половиной дефекта #71 — пути запуска
// расходились молча, потому что каждый решал про порт сам.
//
//   ./scripts/app-port.mjs        печатает, например, 3310
import { register } from "node:module";

// Хук ставится ДО первого импорта из src/: без него Node не знает ни псевдонима `@/`,
// ни импортов без расширения. Зависимостей проекта хук не требует — а это важно:
// `up` спрашивает порт раньше, чем ставит node_modules.
register("./src-resolve-hook.mjs", import.meta.url);

const { appPort } = await import("../src/blocks/core/app-port.ts");

// Отказ не глушим: без порта `up` не должен продолжать на умолчании — молча взятый
// чужой порт и есть та беда, ради которой источник сведён в одно место.
process.stdout.write(`${String(appPort())}\n`);
