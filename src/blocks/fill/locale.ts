// Текст ПУНКТА на языке экрана заполнения — единственное, что осталось здесь своего.
//
// Само правило «чей это язык» (пиццерия → устройство → продукт, D122) переехало в
// `core/store-locale.ts` при T273: поверхностей пиццерии оказалось больше одной — рядом
// с экраном заполнения встала печатная наклейка станции, которую вешают на кухне, а блок
// `qr` до `fill` по графу блоков не дотягивается и не должен. Правило там одно на
// продукт, а не скопировано сюда и туда: копия правила о языке уже стоила проекту #133
// и T268, и оба раза компилятор про копию молчал.
//
// Здесь остаётся выбор текста из того, что завёл методист. Это не про язык запроса, а
// про содержимое чек-листа, и общего у него с наклейкой нет: у наклейки текстов,
// заведённых по языкам, не бывает вовсе.
import type { Locale } from "@/blocks/core/locale";

/**
 * Текст на первом языке цепочки, который у него есть. Если методист завёл пункт
 * на языке вне цепочки — показывается хоть что-нибудь: пустая строка на экране
 * сотрудника хуже строки на чужом языке.
 */
export function pickFillText(
  text: Readonly<Record<string, string>>,
  locales: readonly Locale[],
): string {
  for (const locale of locales) {
    const value = text[locale];
    if (value !== undefined && value !== "") return value;
  }
  return Object.values(text).find((value) => value !== "") ?? "";
}
