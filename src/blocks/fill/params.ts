// Параметры адреса публичного экрана станции.
//
// Имя записано один раз: его строит экран выбора и читает страница маршрута. Две
// одинаковые буквы в разных файлах дают одинаковый результат ровно до дня, когда имя
// сменят, — и разъедутся молча (тот же класс, за который продукт уже заплатил
// четырьмя копиями адресов кабинета, #11).
import { PUBLIC_FILL_PREFIX } from "@/blocks/core/public-routes";

/** `?c=<id чек-листа>` — какой из открытых сейчас чек-листов станции показывать (#60). */
export const CHECKLIST_PARAM = "c";

/**
 * Заголовок запроса, которым посредник называет корневой разметке КОД СТАНЦИИ.
 *
 * Зачем он вообще нужен. Язык этой поверхности принадлежит пиццерии (D122), а знает
 * пиццерию только база. Корневая разметка рендерится РАНЬШЕ страницы и спросить её не
 * может (взаимная блокировка), поэтому язык документа она обязана посчитать сама — а для
 * этого ей нужен код с наклейки. Из адреса она его не видит: `params` динамического
 * сегмента достаются странице и разметке ПОД ним, а не корневой. Посредник адрес видит,
 * и он и так стоит на `/s/:path*` ради одноразового ключа политики (T071) — значит ему
 * и называть. В базу за языком страны ходит уже разметка: посреднику туда хода нет.
 *
 * Прежде этим заголовком ехал ГОТОВЫЙ язык документа, посчитанный из `Accept-Language`, —
 * и это и был дефект T270: посредник называл язык телефона, а экран рисовал язык
 * пиццерии, то есть документ обещал не то, что в нём написано. Экранный диктор и
 * браузерный перевод верят атрибуту, а не буквам.
 *
 * Подделать заголовок может и клиент: маршрутов без посредника продукт не запрещает.
 * Нового он этим не получает — по коду станции и так открыт `GET /s/<код>`, то есть тот
 * же запрос в базу, — а подделавший меняет язык страницы, которую сам же и смотрит.
 */
export const FILL_STATION_CODE_HEADER = "x-fill-station-code";

/**
 * Код станции из адреса — ровно так, как его разберёт сам маршрут `s/[code]`.
 *
 * Один сегмент и только он: `/s/abc/def` маршруту не подходит, и назвать по нему
 * пиццерию значило бы объявить язык страницы, которой нет. Не разобрали — `null`, и
 * тогда язык документа считается как у всего продукта, из `Accept-Language`. Расхождения
 * это не даёт: там, где пиццерии нет, цепочка заполнения и общий выбор языка продукта
 * отвечают одинаково (`pickFillLocales(…, null)[0]` и `pickLocale` — оба «язык телефона,
 * если продукт на нём говорит, иначе язык продукта»).
 */
export function stationCodeFromPath(pathname: string): string | null {
  if (!pathname.startsWith(PUBLIC_FILL_PREFIX)) return null;

  const segment = pathname.slice(PUBLIC_FILL_PREFIX.length);
  if (segment === "" || segment.includes("/")) return null;

  try {
    // Адрес приезжает закодированным, а странице `params.code` достаётся разобранным:
    // без этого шага две стороны сравнивали бы разные строки.
    return decodeURIComponent(segment);
  } catch {
    // Испорченная последовательность процентов. Кода здесь нет — значит и пиццерии нет.
    return null;
  }
}
