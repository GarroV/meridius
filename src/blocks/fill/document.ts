// Язык публичного экрана заполнения — ОДНО решение на запрос, и его берут оба: документ
// и содержимое.
//
// Зачем это отдельным файлом (T270). Решение о языке принимали два места: корневая
// разметка ставила `<html lang>` по `Accept-Language`, потому что пиццерию она не знала,
// а экран рисовал текст на языке пиццерии (D122). Замер на приёмке волны 14: русский
// телефон получал `<html lang="ru">` на странице, где написано `Morning opening —
// Kitchen`. Человек расхождения не видит — его видят экранный диктор, который читает
// английские слова по русским правилам, и браузерный перевод, который предлагает
// перевести страницу на язык, на котором она уже написана. Атрибут `lang` — это то, что
// документ обещает о своём содержимом, и обещание было ложным.
//
// Лечится не вторым вычислением в правильном месте, а тем, что вычисление ровно одно:
// два места, обязанные договориться, договариваются до первой правки. Поэтому здесь
// функция, которую зовут и разметка (`src/app/layout.tsx`), и экран
// (`ui/FillScreen.tsx`), — а `cache()` делает её ответ одним на весь запрос.
//
// Почему не своя корневая разметка для `/s/**` через группу маршрутов, как предполагала
// задача: она считала бы язык САМА, отдельно от экрана, то есть оставила бы те же два
// места. А несколько корневых разметок Next разрешает только без `src/app/layout.tsx` —
// значит все прочие маршруты продукта пришлось бы перенести в группы. Разбор — в журнале
// блока.
import { headers } from "next/headers";
import { cache } from "react";

import type { Locale } from "@/blocks/core/locale";
import { storeLocales } from "@/blocks/core/store-locale";

import {
  checkScanAllowed,
  identifyClient,
  trustedProxyHops,
} from "./rate-limit";
import { stationCountryLocale } from "./station";

/** Имя заголовка стоит один раз: язык запроса читается в одном месте (см. `FillScreen`). */
const ACCEPT_LANGUAGE = "accept-language";

export interface FillLanguage {
  /**
   * Цепочка языков по убыванию предпочтения — для текстов самого чек-листа: методист мог
   * завести пункт только на одном языке (см. `core/store-locale.ts`).
   */
  readonly locales: readonly Locale[];
  /** Язык интерфейса И язык документа: одно значение, поэтому разойтись им негде. */
  readonly locale: Locale;
  /**
   * Предел частоты сработал. Ответ на этот вопрос тоже живёт здесь, а не отдельно на
   * экране: он считается ДО похода в базу — иначе не защищал бы её от перебора, — и
   * счётчик обязан щёлкнуть на запрос один раз, кто бы ни спросил первым.
   */
  readonly tooOften: boolean;
}

/**
 * Язык страны пиццерии, а если базы сейчас нет — `null`.
 *
 * Отказ базы здесь НЕ пробрасывается, и это не проглоченная ошибка. Эту функцию зовёт в
 * том числе корневая разметка, а отказ из корневой разметки Next отправляет на последний
 * рубеж (`global-error.tsx`) — англоязычный экран «продукт не завёлся» без каркаса.
 * Сегодня недоступная база даёт сотруднику нормальный экран отказа продукта
 * (`src/app/error.tsx`) на его языке, и менять это на худшее ради атрибута нельзя.
 * Ошибка не теряется: содержимое всё равно пойдёт в базу за чек-листом, упадёт на том же
 * отказе и отдаст экран отказа с кодом события в журнале сервера. Строка в журнал пишется
 * и здесь — чтобы было видно, что язык документа посчитан запасным путём.
 */
async function countryLocaleOrNone(code: string): Promise<string | null> {
  try {
    return await stationCountryLocale(code);
  } catch (error) {
    console.error(
      "Заполнение: язык страны для документа не прочитан, документ объявит язык устройства",
      error,
    );
    return null;
  }
}

/**
 * Решение о языке публичного экрана по коду со наклейки.
 *
 * Под `cache()`: разметка и страница рендерятся в одном проходе, поэтому оба получают
 * ОДИН ответ — не только одинаковый, а буквально тот же. Отсюда два следствия, за
 * которыми иначе пришлось бы следить руками: счётчик частоты щёлкает на запрос один раз,
 * и в базу за станцией уходит один запрос (`stationContext` тоже под `cache()`).
 *
 * Код станции передаётся аргументом, а не читается здесь из заголовка: у страницы он
 * приходит из `params` — то есть от самого маршрута, — и подменять его на своё чтение
 * значило бы снова заводить второй источник одного факта.
 */
export const fillLanguage = cache(
  async (code: string): Promise<FillLanguage> => {
    const requestHeaders = await headers();
    const acceptLanguage = requestHeaders.get(ACCEPT_LANGUAGE);

    const client = identifyClient({
      forwardedFor: requestHeaders.get("x-forwarded-for"),
      // Адреса соединения среда выполнения не даёт: Next подставляет его в тот же
      // заголовок и только когда клиент своего не прислал — отличить одно от другого
      // нечем. Появится источник адреса — он подставляется сюда, и предел оживает сам.
      peerAddress: null,
      trustedProxyHops: trustedProxyHops(process.env),
    });
    // Предел на клиента применяется, только когда клиентов есть чем различать.
    // Один общий ключ превратил бы его в рубильник на всю сеть (см. `identifyClient`).
    const tooOften =
      client !== null && !checkScanAllowed(client, new Date()).allowed;

    // Пиццерии нет — значит нет и её языка, и остаётся цепочка без первого звена:
    // телефон, а за ним язык продукта. Так же считается и отказ по неизвестному коду:
    // за подобранным кодом пиццерии нет никакой, брать язык неоткуда.
    const countryLocale = tooOften ? null : await countryLocaleOrNone(code);
    const locales = storeLocales(acceptLanguage, countryLocale);

    // Первое звено цепочки — язык интерфейса, и оно есть всегда: тип цепочки это и
    // говорит, поэтому запасного варианта здесь нет. Он был бы веткой, в которую
    // никогда не заходят, — то есть непроверяемой.
    return { locales, locale: locales[0], tooOften };
  },
);
