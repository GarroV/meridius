/**
 * Часы перерисовки страницы: вкладка сама не узнает, что проход обхода закрылся.
 *
 * Разметку отрисовал сервер, и с тех пор она не менялась; проход и просрочку считает
 * он же по местному времени пиццерии (D026), потому что часы кухонного планшета врут.
 * Значит, к ближайшей границе прохода вкладка обязана сходить к серверу заново — сама
 * досчитать она не вправе.
 *
 * Почему это отдельный модуль, а не пара строк внутри плашки. Часы обязаны
 * ПЕРЕВЗВОДИТЬСЯ, когда очередная величина совпала с предыдущей: сетка «каждые
 * полчаса» после каждой границы отдаёт ровно те же 1800 секунд. Внутри компонента это
 * держалось на зависимостях эффекта — то есть на том, что React сравнивает значения:
 * совпало, эффект не перезапущен, а его таймер уже отработал и второй раз не сработает.
 * Выглядело бы это так: первая просрочка показалась, следующие молча нет (T138).
 * Проверить такое в браузере нельзя — самая частая настоящая настройка 10 минут, и
 * сквозной сценарий столько не ждёт. Здесь же перевзвод — своё поведение модуля, и
 * поддельные часы проверяют его за миллисекунды (T191).
 */

const MS = 1000;

/**
 * Не меньше секунды: нулевая задержка закрутила бы вкладку в петлю обновлений — сервер
 * отвечает «граница прямо сейчас», вкладка бежит за ответом, получает то же самое.
 */
const MIN_DELAY_SECONDS = 1;

/**
 * Часы среды. Подменяются в проверках, чтобы не ждать настоящих десяти минут.
 *
 * Заведённый таймер отдаётся СНЯТИЕМ, а не опознавателем: у браузера это число, у
 * Node — объект, и общего типа у них нет. Замыкание убирает вопрос вовсе.
 */
interface RefreshClockTimers {
  readonly setTimer: (run: () => void, ms: number) => () => void;
}

const environmentTimers: RefreshClockTimers = {
  setTimer: (run, ms) => {
    const id = globalThis.setTimeout(run, ms);
    return () => {
      globalThis.clearTimeout(id);
    };
  },
};

export interface RefreshClockOptions {
  /**
   * Через сколько секунд состояние может измениться само; `null` — уже не изменится.
   * Спрашивается заново перед каждым взводом: после похода к серверу величина бывает
   * другой, и держать её копию в часах значило бы завести второй источник правды.
   */
  readonly nextChangeInSeconds: () => number | null;
  /** Сходить к серверу за свежим состоянием. */
  readonly onDue: () => void;
  readonly timers?: RefreshClockTimers;
}

/**
 * Заводит часы и возвращает их остановку. Остановка обязательна при уходе со страницы:
 * иначе брошенный таймер дёрнет перерисовку уже снятого экрана.
 */
export function startRefreshClock({
  nextChangeInSeconds,
  onDue,
  timers = environmentTimers,
}: RefreshClockOptions): () => void {
  let cancel: (() => void) | null = null;

  const arm = (): void => {
    const seconds = nextChangeInSeconds();
    if (seconds === null) return;

    cancel = timers.setTimer(
      () => {
        cancel = null;
        onDue();
        // Тот самый перевзвод. Он стоит ПОСЛЕ похода к серверу, а не вместо него:
        // следующая граница может оказаться и той же величины, и другой — величину
        // спрашиваем заново, а не запоминаем.
        arm();
      },
      Math.max(MIN_DELAY_SECONDS, seconds) * MS,
    );
  };

  arm();

  return () => {
    if (cancel === null) return;
    cancel();
    cancel = null;
  };
}
