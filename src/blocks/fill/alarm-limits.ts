// Пределы будильника — отдельным чистым модулем, а не рядом с запросами.
//
// Панель будильников работает в браузере, а `alarms.ts` ввозит вход блока `data`, то есть
// драйвер `pg`: значение, взятое оттуда, роняет клиентскую сборку целиком (проверено
// настоящей сборкой при зелёных тестах — см. хвост `src/blocks/data/index.ts`). Тот же
// приём и по той же причине уже применён к правилам заполнения.
//
// Числа здесь рабочие. В базе стоит свой предел на подпись, вдвое шире: там заслон
// от мусора, здесь мерка продукта.

/**
 * `maxPerStationPerWindow` — не украшение, а заслон: точка записи публичная, и без
 * потолка один подобранный код набивал бы станции сотни записок. Двенадцать — с запасом
 * к работе: за смену вручную заводят единицы, а панель на 375 px больше и не показать.
 *
 * Считается он на проход окна чек-листа, а не на местные сутки: по тем же границам, по
 * которым будильник живёт и показывается (D090). Разойдись они — на экране было бы
 * меньше строк, чем разрешено, а отказ «больше нельзя» всё равно приходил бы.
 */
export const ALARM_LIMITS = {
  maxLabelLength: 120,
  maxPerStationPerWindow: 12,
} as const;
