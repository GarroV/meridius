// Отказы выпуска пина, которые продукт бросает сам, а не получает от базы.
//
// Отдельным файлом без единого импорта: разбору отказа (`issue-failure.ts`) нужен класс,
// а не текст сообщения, — сравнение по тексту разошлось бы с ним при первой же правке.

/**
 * Свободный код не нашёлся за несколько попыток. Временное состояние: истёкшие коды
 * снимает следующий же выпуск, и через пять минут набор снова свободен.
 */
export class PinsExhaustedError extends Error {
  constructor() {
    super(
      "Привязка планшета: свободный код не нашёлся за несколько попыток — живых пинов слишком много",
    );
    this.name = "PinsExhaustedError";
  }
}
