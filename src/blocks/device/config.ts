// Секрет подписи куки планшета. Значения живут только в окружении: в git попадает лишь
// `.env.example` с именами (принципы проекта).
//
// Секрет СВОЙ, отдельный от админского, и это не симметрия ради симметрии: у планшета в
// пиццерии и у методиста разные уровни доверия, а общий ключ стёр бы разницу — утёкший
// секрет планшета печатал бы сессии кабинета.
const SECRET_VARIABLE = "DEVICE_SESSION_SECRET";

// 32 знака ≈ 192 бита при base64: подпись куки перестаёт быть подбираемой.
const MIN_SECRET_LENGTH = 32;

/**
 * Значение из `.env.example`. Файл лежит в git, поэтому этот секрет знает всякий, кто
 * видел репозиторий: для локальной разработки годится, для площадки — нет. Забытый в
 * проде пример означал бы, что куку планшета подписывает любой читатель репозитория,
 * поэтому на `NODE_ENV=production` он отказывает. Что константа всё ещё совпадает с самим
 * файлом, проверяет `config.test.ts`: разъехаться молча они не могут.
 */
const PUBLISHED_DEV_SECRET =
  "local-development-only-device-secret-not-a-secret";

/**
 * Секрет подписи куки привязанного планшета.
 *
 * Отказ, а не тихое умолчание: без секрета проверить подпись нечем, и «планшет не узнан»
 * на каждый запрос выглядело бы как отвязка, которой не было.
 */
export function deviceSessionSecret(): string {
  const value = process.env[SECRET_VARIABLE];
  if (value === undefined || value.trim() === "") {
    throw new Error(
      `${SECRET_VARIABLE}: переменная окружения не задана, привязка планшета не работает. См. .env.example`,
    );
  }

  if (value === PUBLISHED_DEV_SECRET && process.env.NODE_ENV === "production") {
    throw new Error(
      `${SECRET_VARIABLE}: значение взято из .env.example — оно опубликовано в git и на площадке куку планшета не подписывает. Задайте своё, см. .env.example`,
    );
  }

  if (value.length < MIN_SECRET_LENGTH) {
    throw new Error(
      `${SECRET_VARIABLE}: короче ${String(MIN_SECRET_LENGTH)} знаков — подпись куки планшета подбирается. Сгенерировать: openssl rand -base64 48`,
    );
  }

  // Один ключ на две куки стёр бы разницу в доверии, ради которой секрет и заведён
  // отдельным. Совпадение — это настройка, при которой защита выключена молча.
  if (value === process.env["SESSION_SECRET"]) {
    throw new Error(
      `${SECRET_VARIABLE}: совпадает с SESSION_SECRET. Секрет планшета обязан быть своим — иначе утёкший ключ кухонного планшета печатает сессии кабинета`,
    );
  }

  return value;
}
