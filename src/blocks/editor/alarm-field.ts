/** Самая длинная отсрочка от открытия пункта: полсуток — дольше смена не стоит. */
export const MAX_ALARM_DELAY_MINUTES = 720;

/** Отсрочка, которую поле предлагает, когда методист переключился на «через». */
export const DEFAULT_ALARM_DELAY_MINUTES = 30;

/** Час будильника «ЧЧ:ММ» в сутках: 24:00 законно только как конец окна, не как звонок. */
export const ALARM_TIME_PATTERN = /^([01]\d|2[0-3]):[0-5]\d$/;
