"use client";

import { useEffect, useState } from "react";

/**
 * `true`, когда компонент уже смонтирован на клиенте, то есть его обработчики на месте.
 *
 * Зачем это нужно снаружи. Разметку клиентского компонента отдаёт сервер, и до
 * гидратации (а при переходе внутри приложения — до того, как переход доедет) экран
 * выглядит совершенно рабочим: элементы в DOM, они принимают нажатие и ввод — и НЕ
 * ДЕЛАЮТ НИЧЕГО, потому что обработчика ещё нет. Снаружи эти два состояния
 * неразличимы, а разница между ними — целое действие методиста.
 *
 * Атрибут `data-live` ставится значением этого признака, то есть после коммита:
 * раз он появился, обработчик заведомо на месте. Это тот же род фактов о разметке,
 * что `data-testid` рядом, и он же честно описывает вторую половину прогрессивного
 * улучшения — первую описывает кнопка в `<noscript>` там, где она есть.
 *
 * Тот же приём и по той же причине применён в ленте (`FeedFilterSelects`, T106);
 * здесь он вынесен в одно место, потому что опереться на него нужно трём экранам
 * сразу: спискам фильтра, редактору чек-листа и правке блока библиотеки (T121).
 *
 * Файл намеренно `.tsx`: из подсчёта покрытия разметка исключена, а проверяется этот
 * признак ровно тем, ради чего заведён, — сквозными сценариями в настоящем браузере,
 * где отсутствие `data-live` роняет шаг с внятным текстом.
 */
export function useLive(): boolean {
  const [live, setLive] = useState(false);
  // Пустые зависимости: факт «страница ожила» случается один раз за жизнь компонента.
  useEffect(() => {
    setLive(true);
  }, []);
  return live;
}
