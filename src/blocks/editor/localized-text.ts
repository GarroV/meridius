// Откат по языкам для поля ВВОДА (T174). Отдельный файл без единого импорта — тот же
// урок, что у `uuid.ts`: эту функцию вызывают клиентские поля редактора (`ItemRow`,
// `SectionCard`, `TableColumns`), и она уезжает в браузерный бандл вместе с ними. Импорт
// отсюда чего угодно из `@/blocks/data` потянул бы за собой пул подключений и драйвер
// базы — сборка админки падает на этом с «Module not found: Can't resolve 'dns'».
//
// Экраны ПОКАЗА (предпросмотр, список, панели) решали ту же задачу шестью копиями одной
// строки `text[locale] ?? Object.values(text)[0] ?? ""` — «пустой заголовок хуже
// чужого». Поля ввода были устроены иначе, `value={item.title[locale] ?? ""}`: без
// отката на другой язык методист видел пустое поле там, где текст в данных есть, просто
// на другом языке (заведено в английском окне, открыто в русском интерфейсе). Здесь та
// же логика для обеих сторон экрана — и для чтения (эта функция), и для правки: правка
// по-прежнему пишет в язык интерфейса, второй язык не затирается (решение блока).

/**
 * Текст на языке интерфейса; если под ним пусто или ничего нет — первый непустой из
 * объекта; если непустых нет вовсе — пустая строка. Порядок ключей объекта здесь не
 * решает: язык интерфейса проверяется первым и побеждает первый ключ, даже если черновик
 * начался на другом языке.
 */
export function pickEditorText(
  text: Readonly<Record<string, string>> | undefined,
  locale: string,
): string {
  if (text === undefined) return "";
  const own = text[locale];
  if (own !== undefined && own !== "") return own;
  for (const value of Object.values(text)) {
    if (value !== "") return value;
  }
  return "";
}
