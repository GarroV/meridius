// Кому копировать шаблон при раскатке.
//
// Проверка стоит тут, а не сводится к прогону экрана, по цене ошибки — и она тихая в
// обе стороны. Лишняя копия: на станции два одинаковых чек-листа, и сотрудник не
// понимает, какой заполнять. Пропущенная: станция осталась без чек-листа, а человек
// уверен, что раскатал на всю страну, и узнает об этом через неделю от смены.
import { describe, expect, test } from "vitest";

import { plannedCopies } from "./templates";

describe("кому копировать шаблон", () => {
  test("копируем всем выбранным, если копий ещё нет", () => {
    // Arrange
    const stationIds = ["a", "b", "c"];

    // Act
    const targets = plannedCopies({ stationIds, alreadyHave: [] });

    // Assert
    expect(targets).toEqual(["a", "b", "c"]);
  });

  test("станцию, где копия этого шаблона уже есть, пропускаем", () => {
    // Иначе повторная раскатка на страну удваивает чек-листы на каждой станции —
    // а раскатывают повторно как раз тогда, когда не уверены, доехало ли.
    const targets = plannedCopies({
      stationIds: ["a", "b", "c"],
      alreadyHave: ["b"],
    });

    expect(targets).toEqual(["a", "c"]);
  });

  test("повтор в самом выборе не превращается в две копии", () => {
    // Дерево выбирают группами: «вся страна» и «эта пиццерия» пересекаются, и одна
    // станция приходит дважды. Для человека это один выбор, а не два.
    const targets = plannedCopies({
      stationIds: ["a", "b", "a"],
      alreadyHave: [],
    });

    expect(targets).toEqual(["a", "b"]);
  });

  test("порядок выбора сохраняется", () => {
    // Порядок — это то, в каком виде человек увидит отчёт о раскатке. Переставленный
    // список читается как «сделано что-то другое».
    const targets = plannedCopies({
      stationIds: ["c", "a", "b"],
      alreadyHave: [],
    });

    expect(targets).toEqual(["c", "a", "b"]);
  });

  test("все выбранные уже имеют копию — копировать некого", () => {
    const targets = plannedCopies({
      stationIds: ["a", "b"],
      alreadyHave: ["a", "b"],
    });

    expect(targets).toEqual([]);
  });

  test("пустой выбор не превращается в раскатку на всех", () => {
    // Защита от самой дорогой опечатки: «ничего не выбрано» обязано означать
    // «ничего не делать», а не «сделать со всеми».
    expect(plannedCopies({ stationIds: [], alreadyHave: ["a"] })).toEqual([]);
  });
});
