// Опознание идентификатора. Отдельный файл без единого импорта — и это его смысл,
// а не аккуратность: `filter.ts` попадает в браузер вместе со списками фильтра, а
// `validation.ts`, где эта проверка жила, тянет за собой `@/blocks/data` и драйвер
// базы. Сборка на этом падает («Module not found: Can't resolve 'dns'» в клиентском
// бандле) — поймал её только настоящий `next build`, ни типы, ни тесты этого не видят.

const UUID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** Строка похожа на идентификатор строки базы. */
export function isUuid(value: string): boolean {
  return UUID_PATTERN.test(value);
}
