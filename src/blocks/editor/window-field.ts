// Окно смены в форме: одно поле, которое отправляет сам список на экране.
//
// Почему одним полем, а не парой `windowStart`/`windowEnd`. Пара уезжала скрытыми
// полями, посчитанными из состояния React, а список окна стоял без `name` — то есть на
// сервер уходила КОПИЯ выбора, а не выбор. Копия отстаёт: выбор, сделанный до того как
// экран ожил, в состояние не попадает, и чек-лист заводится на утро при выбранном
// вечере — молча (T129, измерено зондом 11.09.2026: на экране «вечер», в скрытом поле
// 06:00, в базе окно 06:00–11:00). Именованный список отправляет то, что на нём выбрано,
// и делает это даже без единого скрипта — проверено сценарием, который отключает их все.
//
// Здесь же лежат сами окна: раньше их было два одинаковых списка — на заведении и на
// правке, — и разъехаться они могли бесшумно.

/** Окно времени чек-листа: границы в виде «ЧЧ:ММ». */
export interface WindowValue {
  start: string;
  end: string;
}

/** Имя поля формы. Одно на обе формы редактора — контракт с `action-input.ts`. */
export const WINDOW_FIELD = "window";

/**
 * Имена полей «своего окна» — двух настоящих полей времени рядом со списком (T185).
 *
 * Это НЕ возвращение пары `windowStart`/`windowEnd`, которую убрал T129. Та пара была
 * КОПИЕЙ выбора: её считало состояние React и отправляло скрытыми полями, отставая от
 * того, что методист видел на экране. Здесь наоборот — отправляет ровно то поле, в
 * которое методист напечатал время, и работает это даже без единого скрипта. Имена
 * выбраны другие, чтобы поиск по репозиторию не сводил два разных случая в один.
 */
export const WINDOW_FROM_FIELD = "windowFrom";
export const WINDOW_TO_FIELD = "windowTo";

// Границы едут одним значением, поэтому между ними нужен знак, которого во времени
// быть не может. Двоеточие занято, дефис читается как диапазон в подписях.
const SEPARATOR = "|";

/**
 * Готовые окна эталона — быстрый выбор для трёх обычных случаев станции.
 *
 * Прежняя формулировка здесь звучала так: «произвольного времени в продукте нет
 * НАМЕРЕННО: у станции случаев по сути три, а конструктор времени — лишние касания на
 * каждом заведении». Намеренным это было по эталону и остаётся верным для обычного дня,
 * но 17.09.2026 (T185) выяснилось, чего оно стоит: в боевых данных живут окна 05:00–17:00
 * и 06:00–23:00 — то есть смены, которые методист не мог завести руками ВООБЩЕ. Поэтому
 * список остался как есть, а рядом появилось своё окно временем (`windowFromFields`):
 * развилку «пресеты неполны или нужен произвольный ввод» это не закрывает, а оставляет
 * открытой в обе стороны — решать владельцу.
 *
 * Ключ — ключ словаря (`editor.form.*`), чтобы подпись жила в словаре, а не в коде.
 */
export const WINDOW_PRESETS = [
  { labelKey: "windowMorning", value: { start: "06:00", end: "11:00" } },
  { labelKey: "windowEvening", value: { start: "20:00", end: "00:00" } },
  { labelKey: "windowAny", value: { start: "00:00", end: "24:00" } },
] as const;

/** Значение поля формы для окна: «06:00|11:00». */
export function windowFieldValue(window: WindowValue): string {
  return `${window.start}${SEPARATOR}${window.end}`;
}

/**
 * Обратный разбор — на сервере и в списке экрана правки.
 *
 * Ничего не проверяет: время проверяет `parseWindow` на границе слоя данных, и делать
 * это дважды значит завести второе место, где правила окна написаны своими словами.
 * Отсутствующая половина приходит пустой строкой — она и получит внятный отказ.
 */
export function parseWindowField(raw: string): WindowValue {
  const [start = "", end = ""] = raw.split(SEPARATOR);
  return { start, end };
}

/**
 * Окно из формы заведения: своё, если оно задано ЦЕЛИКОМ, иначе выбранное в списке.
 *
 * Почему «целиком», а не «хоть что-то». Методист начал набирать своё окно и передумал —
 * в поле осталась одна граница. Взять её значило бы завести чек-лист с пустой второй
 * границей и отказом там, где человек уже выбрал готовое окно и ничего плохого не делал.
 * Полупустое своё окно поэтому просто не считается заданным.
 *
 * Правило живёт здесь, а не в разметке формы, по той же причине, по которой здесь живут
 * сами окна: форм две, и написанное словами дважды разъезжается молча.
 */
export function windowFromFields(
  listValue: string,
  from: string,
  to: string,
): WindowValue {
  const start = from.trim();
  const end = to.trim();
  if (start !== "" && end !== "") return { start, end };
  return parseWindowField(listValue);
}
