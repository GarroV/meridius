// Окно смены в форме: одно поле, которое отправляет сам список на экране.
//
// Почему одним полем, а не парой `windowStart`/`windowEnd`. Пара уезжала скрытыми
// полями, посчитанными из состояния React, а список окна стоял без `name` — то есть на
// сервер уходила КОПИЯ выбора, а не выбор. Копия отстаёт: выбор, сделанный до того как
// экран ожил, в состояние не попадает, и чек-лист заводится на утро при выбранном
// вечере — молча (T129, измерено зондом 11.09.2026: на экране «вечер», в скрытом поле
// 06:00, в базе окно 06:00–11:00). Именованный список отправляет то, что на нём выбрано,
// и делает это даже без единого скрипта — проверено сценарием, который отключает их все.
//
// Здесь же лежат сами окна: раньше их было два одинаковых списка — на заведении и на
// правке, — и разъехаться они могли бесшумно.

/** Окно времени чек-листа: границы в виде «ЧЧ:ММ». */
export interface WindowValue {
  start: string;
  end: string;
}

/** Имя поля формы. Одно на обе формы редактора — контракт с `action-input.ts`. */
export const WINDOW_FIELD = "window";

// Границы едут одним значением, поэтому между ними нужен знак, которого во времени
// быть не может. Двоеточие занято, дефис читается как диапазон в подписях.
const SEPARATOR = "|";

/**
 * Готовые окна эталона. Произвольного времени в продукте нет намеренно: у станции
 * случаев по сути три, а конструктор времени — лишние касания на каждом заведении.
 * Ключ — ключ словаря (`editor.form.*`), чтобы подпись жила в словаре, а не в коде.
 */
export const WINDOW_PRESETS = [
  { labelKey: "windowMorning", value: { start: "06:00", end: "11:00" } },
  { labelKey: "windowEvening", value: { start: "20:00", end: "00:00" } },
  { labelKey: "windowAny", value: { start: "00:00", end: "24:00" } },
] as const;

/** Значение поля формы для окна: «06:00|11:00». */
export function windowFieldValue(window: WindowValue): string {
  return `${window.start}${SEPARATOR}${window.end}`;
}

/**
 * Обратный разбор — на сервере и в списке экрана правки.
 *
 * Ничего не проверяет: время проверяет `parseWindow` на границе слоя данных, и делать
 * это дважды значит завести второе место, где правила окна написаны своими словами.
 * Отсутствующая половина приходит пустой строкой — она и получит внятный отказ.
 */
export function parseWindowField(raw: string): WindowValue {
  const [start = "", end = ""] = raw.split(SEPARATOR);
  return { start, end };
}
