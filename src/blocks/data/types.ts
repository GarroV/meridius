// Формат разметки чек-листа и ответов. Это контракт между редактором и экраном
// заполнения (docs/furca/plan.md, «Контракты между блоками»): editor пишет, fill читает.

/** Текст на языках продукта: ключ — код языка ("ru", "en"). */
export type LocalizedText = Record<string, string>;

/**
 * Тип ответа на пункт: да/нет, число с диапазоном, свободный текст, таблица.
 *
 * `table` — журнал замеса теста (D074): колонки задаёт методист, строки заводит
 * сотрудник по ходу смены. Норма над колонкой — подсказка методиста, а не правило:
 * провалить табличный пункт нельзя, ровно как свободный текст.
 */
export type ItemType = "bool" | "number" | "text" | "table";

/**
 * Колонка табличного пункта (D074). `norm` — та самая строка норм, что в бумажном
 * журнале стоит над колонкой: «16–26 °C», «200 г», «медленно — 4 мин».
 *
 * Норма хранится текстом, а не парой чисел, потому что в исходном журнале она текстом
 * и написана: у половины колонок это не диапазон, а указание («медленно — 4 мин,
 * быстро — 5 мин»). Считать по ней продукт не берётся и не обещает.
 */
export interface ItemColumn {
  id: string;
  title: LocalizedText;
  norm?: LocalizedText;
}

/**
 * Строка табличного журнала: значение клетки по опознавателю КОЛОНКИ, а не по её месту
 * в списке. Место меняется правкой колонок, опознаватель — нет, а уже сохранённое
 * заполнение читается СВОИМ снимком колонок (принцип 3, D002).
 */
export type TableRow = Record<string, string>;

/**
 * Насколько тяжело не выполнить пункт (D056).
 * `critical` — не выполнить нельзя: входит в любой режим смены и поднимает тревогу.
 * `major` — деньги и оборудование: выпадает только в критичной смене.
 * `normal` — обычная работа: остаётся лишь в полной смене.
 */
export type Severity = "critical" | "major" | "normal";

/**
 * Режим смены пиццерии (D055, D056): сколько людей сегодня в графике и, значит,
 * какие уровни пунктов вообще показывать.
 */
export type ShiftMode = "normal" | "reduced" | "critical";

/**
 * Отрезок расписания периодической проверки (D075).
 *
 * `to` — конец периода, а НЕ время последнего обхода: «с 08:00 до 12:00 каждый час»
 * это обходы в 8, 9, 10 и 11, а последний из них длится до 12:00. Иначе автор
 * расписания каждый раз гадал бы, входит ли граница, и половина сеток оказалась бы
 * короче задуманного на один обход — молча.
 */
export interface ScheduleSegment {
  /** Местное время начала отрезка, «ЧЧ:ММ». */
  from: string;
  /** Местное время конца отрезка, «ЧЧ:ММ». */
  to: string;
  /** Шаг внутри отрезка в минутах. */
  everyMinutes: number;
}

/** Окно работы чек-листа в местном времени пиццерии; может идти через полночь. */
export interface ChecklistWindow {
  start: string;
  end: string;
}

export interface Item {
  id: string;
  title: LocalizedText;
  type: ItemType;
  severity?: Severity;
  /**
   * Признак до появления уровней. Не пишется больше нигде, но читается вечно:
   * он лежит внутри уже опубликованных версий и снимков заполнений, которые
   * переписывать запрещено (принцип 3, D002). Разбирает его `severityOf`.
   * @deprecated используйте `severity`
   */
  critical?: boolean;
  min?: number;
  max?: number;
  hint?: LocalizedText;
  /**
   * Расписание периодической проверки (D075). Нет поля или пустой список — пункт
   * обычный и заполняется вместе с остальными; миграции данных нет, всё
   * опубликованное до появления расписания читается как прежде (принцип 3, D002).
   */
  schedule?: ScheduleSegment[];
  /**
   * Как часто повторять сигнал о просроченном обходе: 10, 20 или 60 минут (D068).
   * Нет поля — не оповещать; ноль для этого не используется, чтобы «молчать» и
   * «звонить каждые ноль минут» не оказались одним значением. Смысл есть только
   * рядом с `schedule`: без расписания просрочке взяться неоткуда.
   */
  remindEveryMinutes?: number;
  /**
   * Колонки табличного пункта (D074). Есть только у `type: "table"`; у остальных
   * родов пункта поле не хранится вовсе — невидимое на экране значение, доехавшее
   * до базы, останется там навсегда.
   */
  columns?: ItemColumn[];
}

/**
 * Секция — группа пунктов со своим заголовком (D012).
 * `source` показывает происхождение: свои пункты или вставка блока библиотеки (D011).
 * В опубликованной версии внутри всегда лежит снимок пунктов, а не ссылка на живой блок,
 * иначе правка блока меняла бы историю задним числом (принцип 3).
 */
export interface Section {
  id: string;
  title: LocalizedText;
  source: "own" | { blockId: string };
  items: Item[];
}

/**
 * Значение ответа: по типу пункта — да/нет, число, свободный текст или строки
 * табличного журнала (D074).
 */
export type AnswerValue = boolean | number | string | TableRow[];

/** Ответ на пункт: значение по типу пункта, комментарий и момент ответа с устройства. */
export interface Answer {
  itemId: string;
  value: AnswerValue;
  comment?: string;
  at: number;
}

/**
 * Состояние версии чек-листа.
 * `draft` — рабочий черновик методиста, `published` — та, что отдаётся на станцию,
 * `archived` — прежняя опубликованная. Содержимое версии не меняется никогда;
 * публикация следующей версии переводит прежнюю в `archived` и только.
 */
export type VersionStatus = "draft" | "published" | "archived";
