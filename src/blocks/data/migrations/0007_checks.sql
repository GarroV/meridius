-- Отметки периодических проверок — обходов (D066, D075, T135).
--
-- Таблица только пополняется: повторный обход в тот же час — новая строка, а не правка
-- прежней. Пропуск здесь не хранится и храниться не будет — это отсутствие строки против
-- сетки расписания, и выводится он при чтении (D053). Хранимый пропуск потребовал бы
-- фоновой работы, которая его проставляет, и колонки состояния, которую после каждого
-- сбоя чинят руками.
CREATE TABLE "checks" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  -- Станция запоминается здесь так же, как в заполнениях: перенос чек-листа на другую
  -- станцию не должен задним числом переписывать, где обход делали (принцип 3).
  "station_id" uuid NOT NULL REFERENCES "stations"("id") ON DELETE RESTRICT,
  -- Версия, на экране которой стояла отметка. Читаются отметки по чек-листу, а не по
  -- версии: методист публикует следующую версию посреди смены (T041), и утренние обходы
  -- не имеют права исчезнуть с экрана станции.
  "version_id" uuid NOT NULL REFERENCES "checklist_versions"("id") ON DELETE RESTRICT,
  "item_id" text NOT NULL,
  -- Местная дата прохода ОКНА, а не дата отметки: у окна через полночь обход в час ночи
  -- относится к проходу, начавшемуся вчера (D055).
  "local_date" date NOT NULL,
  -- Минуты от начала окна чек-листа: та же система координат, что у сетки расписания.
  -- Так окно через полночь перестаёт быть особым случаем.
  "interval_start" integer NOT NULL,
  "value" jsonb NOT NULL,
  "comment" text,
  -- Время сервера: отметка обязана помнить тот миг, из которого считался её проход.
  "at" timestamp with time zone DEFAULT now() NOT NULL,
  -- Проход начинается не раньше окна: отрицательное смещение означало бы отметку до
  -- открытия чек-листа, то есть ошибку счёта, а не событие смены.
  CONSTRAINT "checks_interval_start" CHECK ("interval_start" >= 0),
  -- Пределы на строку, а не на документ: строк за смену сотни, и каждая приходит с той
  -- же публичной страницы, что и заполнение.
  CONSTRAINT "checks_value_size" CHECK (pg_column_size("value") <= 4096),
  CONSTRAINT "checks_comment_length" CHECK ("comment" is null or length("comment") <= 2000)
);

-- Главный запрос экрана станции — «отметки этой станции за сегодняшний проход».
CREATE INDEX "checks_station_date_idx" ON "checks" ("station_id", "local_date");
CREATE INDEX "checks_version_idx" ON "checks" ("version_id");
