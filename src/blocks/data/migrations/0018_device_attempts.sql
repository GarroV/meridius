-- Счёт попыток привязки планшета в базе (#144).
--
-- До этой миграции предел попыток на `/pair` жил в памяти процесса: перезапуск снимал
-- его мгновенно, а вторая копия приложения молча удваивала — каждая считала своё, и
-- выглядело это как работающий ограничитель. Теперь счёт один на все копии и переживает
-- перезапуск: строка на пару «бюджет — ключ», окно отсчитывается от первой попытки.
--
-- Бюджетов два, и они не делят счёт: ввод кода на планшете (`/pair`, публичный) и выпуск
-- кода в кабинете (на учётку). Перебор, выбравший бюджет `/pair`, не запирает управляющему
-- выпуск кода, и наоборот.
--
-- Таблица своя, а не `login_attempts`: та — состояние защиты входа в кабинет (блок
-- `auth`), а публичной поверхности привязки знать о входе запрещено (T187).
--
-- Имя бюджета лежит и открытой колонкой: уборка кончившихся окон идёт по бюджету, чтобы
-- счёт одного бюджета не сметался чужим «сейчас». Имя — константа кода, а не данные
-- снаружи; его форма проверяется здесь же.
--
-- Ключ — sha256 от бюджета, области и ключа клиента: адрес приходит подделываемым
-- заголовком, и хранить его продукт не должен (D001). Форма отпечатка проверяется здесь,
-- а не только в коде.
CREATE TABLE "device_attempts" (
	"attempt_key" text PRIMARY KEY NOT NULL,
	"budget" text NOT NULL,
	"window_started_at" timestamp with time zone NOT NULL,
	"attempts" integer NOT NULL,
	CONSTRAINT "device_attempts_attempt_key_shape" CHECK (attempt_key ~ '^[0-9a-f]{64}$'),
	CONSTRAINT "device_attempts_attempts_positive" CHECK (attempts > 0),
	CONSTRAINT "device_attempts_budget_shape" CHECK (budget ~ '^[a-z0-9-]{1,64}$')
);
