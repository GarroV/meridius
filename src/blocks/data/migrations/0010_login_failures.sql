-- Счёт неудачных попыток входа в кабинет переезжает из памяти процесса в базу (T212).
--
-- До этой таблицы счёт жил в Map внутри процесса: после шести промахов вход отвечал
-- «Повторите через 15 минут», а перезапуск процесса снимал отказ мгновенно. То есть
-- защита от подбора единственного пароля продукта (D014: вошедший может всё) держалась
-- на непрерывности процесса, а не на состоянии, — при том что процесс перезапускается
-- сам: выкладка новой версии, падение, `restart: unless-stopped` у стенда.
--
-- Строк здесь заведомо единицы. Запись появляется только на попытке, которую впустил
-- общий потолок (50 неудач за 15 минут), а после потолка не впускается ни одна: больше
-- полусотни живых строк в таблице быть не может. Устаревшие снимаются при следующей
-- же неудаче, поэтому индекса тут нет намеренно — на таком объёме он только мешает.
CREATE TABLE "login_failures" (
	-- Не адрес клиента, а его отпечаток: sha256 от области счёта и ключа клиента.
	-- Адрес приходит заголовком от обратного прокси, то есть подделывается кем угодно
	-- и длины не имеет; в базе продукта такому значению не место ни как данным
	-- (адресов сотрудников продукт не хранит нигде — D001), ни как строке, которую
	-- пишет неопознанный человек из интернета. Проверка формы стоит здесь, в базе:
	-- забытое хэширование в коде не должно означать, что база примет что угодно.
	"attempt_key" text PRIMARY KEY,
	-- Начало окна: отсчёт идёт от ПЕРВОЙ неудачи, а не от последней, иначе попытки
	-- перебирающего продлевали бы отказ администратору бесконечно.
	"window_started_at" timestamptz NOT NULL,
	"failures" integer NOT NULL,
	CONSTRAINT "login_failures_attempt_key_shape" CHECK ("attempt_key" ~ '^[0-9a-f]{64}$'),
	CONSTRAINT "login_failures_failures_positive" CHECK ("failures" > 0)
);
