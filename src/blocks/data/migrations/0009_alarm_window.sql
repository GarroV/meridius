-- Будильник живёт до конца окна работы чек-листа, а не до местной полуночи (D090, T159).
--
-- Почему колонка местных суток уходит целиком. Она и была единицей жизни будильника:
-- сегодняшние строки читались, вчерашние переставали. Владелец эту единицу отменил —
-- пиццерия, работающая до 02:00, обязана ставить будильник на 00:30 в 23:40, а такая
-- запись принадлежит уже СЛЕДУЮЩИМ местным суткам и из выборки «на сегодня» пропадала
-- бы ровно в полночь: сотрудник завёл будильник, а он не прозвонил.
--
-- Новая единица — текущий проход окна чек-листа станции, и его границы считает запрос
-- из часового пояса пиццерии. Хранить для этого нечего: миг звонка в колонке `at` и так
-- отметка с поясом, и сравнение с границами прохода однозначно. Колонка, которая ничего
-- больше не решает, но обязана заполняться при каждой вставке, — источник расхождения,
-- а не запас на будущее.
DROP INDEX IF EXISTS "alarms_station_date_idx";
ALTER TABLE "alarms" DROP COLUMN "local_date";
-- Главный запрос экрана станции стал «будильники станции в границах прохода окна»:
-- отбор идёт по мигу звонка, по нему же и порядок строк в списке.
CREATE INDEX "alarms_station_at_idx" ON "alarms" ("station_id", "at");
