-- «Шаблон обновился — оставить как есть» (D154, D155, T336).
--
-- Копия уже помнит, с какой версии шаблона снята (`source_version`). Этого мало для
-- приглашения, а не требования: страна, решившая «оставить как есть», должна перестать
-- видеть строку «шаблон обновился» — до СЛЕДУЮЩЕГО обновления, а не навсегда.
--
-- Отдельная колонка, а не сдвиг `source_version`: номер источника отвечает на вопрос
-- «с какой версии шаблона снято содержимое копии», и отказ от обновления содержимого не
-- меняет. Сдвиг солгал бы строке происхождения («копия версии 5», а пункты — версии 3) и
-- следующему сравнению: отличия считались бы не от того, что у страны на самом деле.
--
-- Пусто — страна ещё ничего не отклоняла. Колонка без ограничения на «не больше
-- последней версии»: версия шаблона живёт в другой строке, а проверку держит действие.
ALTER TABLE "checklists" ADD COLUMN "source_seen_version" integer;
