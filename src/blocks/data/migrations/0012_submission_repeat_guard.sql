UPDATE "submissions" AS "later"
SET "duplicate" = true
WHERE EXISTS (
  SELECT 1
  FROM "submissions" AS "earlier"
  WHERE "earlier"."version_id" = "later"."version_id"
    AND "earlier"."started_at" = "later"."started_at"
    AND ("earlier"."submitted_at", "earlier"."id") < ("later"."submitted_at", "later"."id")
);--> statement-breakpoint
CREATE UNIQUE INDEX "submissions_one_per_filling_idx" ON "submissions" USING btree ("version_id","started_at") WHERE NOT "duplicate";
