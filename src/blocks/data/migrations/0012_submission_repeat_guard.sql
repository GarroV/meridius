-- Одно заполнение — одна запись, правилом базы (T219).
--
-- Опознаватель заполнения — пара «версия + начало»: начало берётся из пропуска,
-- который сервер выдаёт вместе с экраном, и внутри процесса оно неповторимо (T186).
-- Повтор той же отправки — двойное касание, «отправить ещё раз» после подвисшего
-- ответа, ретрай прокси — код ловил проверкой перед записью. Но проверка не видит
-- запись, которая ещё не зафиксирована, и два одновременных запроса оба слышали
-- «не найдено» и оба писали: в ленте управляющего одна работа стояла дважды.
-- Закрыть это может только правило, которое проверяется в самой вставке, — индекс.
--
-- На живой базе такие пары уже могут лежать, и уникальный индекс на них упал бы:
-- продукт не поднялся бы после раскатки. Удалить лишнюю запись миграция не вправе —
-- история заполнений неприкосновенна (принцип 3), а что делать с повторами прошлого,
-- решает владелец. Поэтому в каждой такой паре поздняя запись помечается как повтор
-- и выводится из-под правила; ни ответ, ни снимок, ни время, ни станция не меняются,
-- и в ленте запись стоит, как стояла. Ранней считается отправленная раньше, при
-- равном времени — с меньшим id: правило должно выбрать ровно одну.
