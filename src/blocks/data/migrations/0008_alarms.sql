-- Будильники станции — записка на сегодня, а не история (D070, T139).
--
-- Почему таблица, а не память процесса: «пережить перезагрузку планшета обязан». Планшет
-- на кухне гаснет, обновляется и перезагружается посреди смены, и будильник, живший в
-- памяти вкладки, исчезал бы ровно тогда, когда он и нужен.
--
-- Почему правило неизменяемости (D002) сюда НЕ распространяется: это не заполнение и не
-- отметка обхода, а записка сотрудника самому себе на ближайшие часы. Её заводят, её
-- снимают, и назавтра её никто не ищет — поэтому и удаление строки здесь законно, и
-- ON DELETE CASCADE у станции: запрещать снос станции из-за записки, которая истекает
-- сегодня ночью, было бы неверно.
CREATE TABLE "alarms" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  -- Будильник принадлежит СТАНЦИИ, а не чек-листу и не версии: на станции может быть
  -- открыто несколько чек-листов (экран выбора), а планшет у неё один, и звонить он
  -- обязан независимо от того, какой чек-лист сейчас открыт.
  "station_id" uuid NOT NULL REFERENCES "stations"("id") ON DELETE CASCADE,
  -- Местные сутки станции, в которых будильник живёт. Это и есть «до конца местных
  -- суток» из D070: назавтра строка просто перестаёт читаться, и регулярности у неё
  -- не появляется ни при каких условиях.
  "local_date" date NOT NULL,
  -- Момент звонка. Считает PostgreSQL из часового пояса пиццерии (D026), второго
  -- календаря в JavaScript продукт не заводит.
  "at" timestamp with time zone NOT NULL,
  "label" text NOT NULL,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  -- Подпись — короткая записка («вынести тесто»), а не докладная. Здесь заслон, а не
  -- рабочая мерка: рабочий предел вдвое меньше и стоит в блоке fill, как у комментария
  -- к ответу. Пустая подпись запрещена: будильник без подписи звонит и не говорит, зачем.
  CONSTRAINT "alarms_label_length" CHECK (length("label") between 1 and 240)
);

-- Главный запрос экрана станции — «будильники этой станции на сегодня».
CREATE INDEX "alarms_station_date_idx" ON "alarms" ("station_id", "local_date");
