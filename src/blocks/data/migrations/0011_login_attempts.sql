-- Счёт входа переименован по сути: в строке лежит число ПОПЫТОК в текущем окне,
-- а не число промахов (T217).
--
-- Что изменилось в самом счёте. Решение «пускать ли» принималось отдельным читающим
-- запросом, а попытка записывалась уже после проверки пароля. Читающий запрос ничего
-- не занимает, поэтому запросы, пришедшие разом, читали одинаковое «ещё не отказ»
-- и доходили до пароля все до одного: предел снимался одновременностью. Теперь попытка
-- сначала занимает место в счёте — тем же запросом, который возвращает её номер, — и до
-- пароля доходит только занявшая место. Считаются поэтому попытки, включая отклонённые;
-- удачная попытка снимает строку целиком.
--
-- Уточнение к комментарию миграции 0010: сказанное там «больше полусотни живых строк
-- быть не может» держалось на том, что строка появляется только у впущенной попытки.
-- Теперь строка появляется у каждой, и потолок числа строк держит сам ключ: клиентский
-- счёт ведётся по корзине (остаток от хэша адреса, 10 000 корзин в блоке `auth`), а не
-- по адресу, поэтому строк в таблице не больше, чем корзин, плюс одна общая.
