// Чем станция не закрыта. Одно место, где продукт решает, что считать дыркой.
//
// Зачем отдельным модулем, а не условием в разметке. Эти признаки — то, ради чего
// раздел станций вообще существует: он показывает не опись сети, а места, где продукт
// молча не работает. Условие, разъехавшееся между списком, фильтром и главной, покажет
// человеку три разных числа дырок на одном и том же состоянии базы — и он справедливо
// перестанет верить всем трём. Поэтому решение одно и проверяется отдельно.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Проект пути (`specs/2026-09-25-user-flow.md`) называл третью
// дырку — «нечем заполнять»: у станции есть чек-лист, но ни наклейки, ни планшета.
// Измерить её нечем: код станции заводится вместе с самой станцией и существует всегда,
// а напечатали наклейку или нет, продукт не видит и видеть не может — печать уходит в
// принтер, а не в базу. Признак, который «почти работает», хуже отсутствующего: человек
// начнёт по нему принимать решения. Поэтому привязка планшета показывается строкой
// состояния, а дыркой не считается, и проект пути поправлен по факту.

/** Станция молчит, если её не заполняли столько часов. Сутки — одна рабочая смена. */
export const SILENT_AFTER_HOURS = 24;

const HOUR_MS = 60 * 60 * 1000;

/**
 * Дырка станции. Их ровно две, и они не складываются: станция без чек-листа не может
 * ещё и молчать — молчать нечему.
 */
export type StationGap =
  /** Чек-листа нет: наклейка на стене откроет пустоту. */
  | "noChecklist"
  /** Чек-лист есть, но за сутки ни одного заполнения. */
  | "silent";

export interface StationFacts {
  /** Сколько чек-листов назначено. Ноль — первая дырка. */
  readonly checklistCount: number;
  /** Последнее заполнение, либо `null` — не заполняли ни разу. */
  readonly lastSubmissionAt: Date | null;
  /**
   * Когда станция заведена. Нужна, чтобы не записывать в молчащие станцию, которую
   * только что создали: у неё ещё не было смены, и красная метка на ней — ложная
   * тревога, от которой человек научится не смотреть на метки вообще.
   */
  readonly createdAt: Date;
}

/** Чем станция не закрыта. Пустой список — со станцией всё в порядке. */
export function gapsOf(facts: StationFacts, now: Date): readonly StationGap[] {
  if (facts.checklistCount === 0) return ["noChecklist"];

  const since = facts.lastSubmissionAt ?? facts.createdAt;
  const quietFor = now.getTime() - since.getTime();

  return quietFor > SILENT_AFTER_HOURS * HOUR_MS ? ["silent"] : [];
}
