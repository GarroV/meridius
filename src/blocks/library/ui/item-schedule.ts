// Регулярность пункта блока библиотеки — относительным отрезком, без часов суток (D097).
//
// Почему не `chipSummary` редактора. Тот показывает «07:00–11:00, каждые 2 часа»: часы
// приходят из окна чек-листа, а у блока окна нет и не заводится — один блок живёт сразу
// в нескольких чек-листах с разными окнами, и второй источник правды об окне разъехался
// бы с тем, что видит заполняющий. Относительный отрезок — ровно то, что блок несёт на
// деле: периодичность без привязки к часам.
//
// Файл чистый: ни разметки, ни словаря. Подпись собирает `ItemScheduleChip` — она
// двуязычна и склоняет числительные, а проверить факт нужно без браузера.
import type { Item } from "@/blocks/data";

/** Что показывает чип пункта блока. */
export type BlockScheduleSummary =
  /** Расписания нет: пункт заполняется один раз за обход. */
  | { readonly kind: "none" }
  /** Один шаг на все отрезки — «каждые 2 часа». */
  | { readonly kind: "every"; readonly everyMinutes: number }
  /**
   * Шаги разные. Схлопнуть их в один нельзя, а показать часы — значит показать окно,
   * которого у блока нет; поэтому перечисляются сами шаги.
   */
  | { readonly kind: "mixed"; readonly steps: readonly number[] };

/**
 * Относительная сводка расписания пункта.
 *
 * Отрезки с одинаковым шагом сливаются в один: без часов суток «07:00–11:00 каждые 2 ч»
 * и «14:00–18:00 каждые 2 ч» — это одно и то же утверждение «каждые 2 часа», и показывать
 * его дважды значило бы показывать различие, которого на экране нет.
 */
export function blockScheduleSummary(item: Item): BlockScheduleSummary {
  const schedule = item.schedule ?? [];
  if (schedule.length === 0) return { kind: "none" };

  const steps = [
    ...new Set(schedule.map((segment) => segment.everyMinutes)),
  ].sort((a, b) => a - b);
  const [only] = steps;
  if (steps.length === 1 && only !== undefined) {
    return { kind: "every", everyMinutes: only };
  }
  return { kind: "mixed", steps };
}
