import type { ReactElement, ReactNode } from "react";

/**
 * Обёртка действий в верхней полосе экранов блока.
 *
 * Зачем она есть. Каркас кабинета кладёт `topbarAction` в ряд без переноса
 * (`AdminShell.tsx`), а сама колонка содержимого растёт по min-content — значит
 * ширина полосы складывается из ширин ВСЕХ действий подряд. На телефоне колонке
 * остаётся 167 px, и подпись периода вместе со ссылкой требуют 175: страница
 * уезжает вбок целиком — вместе с боковым меню, фильтрами и лентой (замер на
 * 375 px: полоса ленты одна давала scrollWidth 383 при clientWidth 375).
 *
 * Перенос внутри своей обёртки снимает это, не трогая чужой каркас: на широком
 * экране всё остаётся в одну строку, как на эталоне, а на узком действия встают
 * друг под друга и прижимаются вправо. Складывается теперь не сумма ширин, а
 * ширина самого широкого действия.
 */
export function TopbarActions({
  children,
}: {
  readonly children: ReactNode;
}): ReactElement {
  return (
    <div className="flex min-w-0 flex-wrap items-center justify-end gap-[var(--space-4)]">
      {children}
    </div>
  );
}
