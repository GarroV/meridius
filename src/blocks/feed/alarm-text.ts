// Что именно случилось: одна тревога — одна формулировка.
//
// Вынесено из разметки полосы отдельным файлом по одной причине: по D063 виды тревоги
// визуально НЕ различаются (ни цвета, ни значка — владелец: «хватит текста»), и текст
// остался единственным, чем управляющий отличает провал от молчания и от незаполненного
// чек-листа. Единственную опору положено держать под проверкой, а разметку полосы
// проверить без браузера нечем — отсюда чистая функция и `alarm-text.test.ts` рядом.
import type { AlarmKind } from "./alarms";

/** Ключ словаря и подстановки к нему: строка полосы больше ничего о словаре не знает. */
export interface AlarmText {
  readonly key: AlarmKind;
  readonly values: Record<string, string | number>;
}

/** Тревога в том виде, в каком формулировка её различает: вид и сколько пунктов. */
export interface AlarmTextInput {
  readonly kind: AlarmKind;
  readonly itemCount: number;
}

/**
 * Формулировка тревоги: ключ словаря и его подстановки.
 *
 * Провалы считают пункты, незаполненный чек-лист называет время закрытия окна — именно
 * это и делает три строки полосы тремя разными событиями. Складывать провал и молчание
 * в одну строку с двумя числами нельзя: за «2 критичных не закрыто» стоят два разных
 * разговора, а тревогу читают с первого раза.
 */
export function alarmText(row: AlarmTextInput, time: string): AlarmText {
  return row.kind === "missed"
    ? { key: "missed", values: { time } }
    : { key: row.kind, values: { count: row.itemCount } };
}
