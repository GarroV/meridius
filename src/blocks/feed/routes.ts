// Адреса блока. Собраны в одном месте: разметка, сквозные сценарии и охрана админки
// ссылаются на строку отсюда, а не на свою копию.
//
// Адрес САМОГО раздела сюда не переписывается: он живёт в `core/admin-sections`, откуда
// его читает и боковое меню. Своя копия строки разъезжается с меню молча — продукт это
// уже проходил, и работающие разделы месяц показывались надписью «Раздел ещё не готов»
// (#11, T074).
import { ADMIN_SECTIONS } from "@/blocks/core/admin-sections";

/** Лента заполнений. */
export const FEED_PATH = ADMIN_SECTIONS.feed.path;

/** Карточка одного заполнения. */
export function submissionPath(id: string): string {
  return `${FEED_PATH}/${encodeURIComponent(id)}`;
}
