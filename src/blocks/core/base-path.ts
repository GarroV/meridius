// Перенаправления при опубликованном базовом пути (D045).
//
// Next обходится с базовым путём по-разному, и разница куплена фактом на живой площадке:
//
//   * `redirect()` ПРИ РЕНДЕРЕ (охрана маршрута, страница) отдаёт заголовок `Location`
//     как написано — базовый путь надо приставить самому, иначе человек уезжает на корень
//     адреса, где на общей площадке живёт соседний сервис;
//   * `redirect()` ВНУТРИ СЕРВЕРНОГО ДЕЙСТВИЯ (`"use server"`) обрабатывает клиентский
//     роутер, и базовый путь он добавляет сам — приставленный вручную даёт `/qr/qr/admin`
//     и честный 404.
//
// Поэтому обёртка стоит только в рендере. Проверено обоими способами по внешнему адресу:
// без неё вход уводил на чужой продукт, с ней в серверном действии — на двойной путь.
//
// Читается из окружения самого процесса: перенаправление собирается на сервере, и
// значение здесь то же, с которым собрана страница.

/** Базовый путь сборки: `/qr` или пустая строка на обычной площадке. */
function basePath(): string {
  const raw = (
    process.env["BASE_PATH"] ??
    process.env["__NEXT_ROUTER_BASEPATH"] ??
    ""
  ).trim();
  if (raw === "") return "";
  const withLeadingSlash = raw.startsWith("/") ? raw : `/${raw}`;
  return withLeadingSlash.endsWith("/")
    ? withLeadingSlash.slice(0, -1)
    : withLeadingSlash;
}

/**
 * Путь для `redirect()`: с базовым путём площадки впереди.
 *
 * Пригодность значения проверяется при старте продукта (`src/startup-checks.ts`),
 * поэтому здесь путь только приставляется.
 */
export function redirectPath<T extends string>(path: T): T {
  return withBasePath(path);
}

/**
 * Путь для нативного `action` обычной GET-формы (фильтры экранов).
 *
 * Отдельно от `<Link>` и роутера: тем базовый путь приставляет сам Next, а атрибут
 * `action` он не трогает — браузер отправляет форму ровно по написанному адресу.
 * На площадке с базовым путём выбор страны в фильтре уводил на `/admin/feed`, то есть
 * на «Такой страницы нет», и экран выглядел упавшим (проверено на стенде 24.09.2026).
 *
 * Важно: `href` ссылки рядом с такой формой (сброс фильтра) остаётся БЕЗ приставки —
 * иначе выходит `/qr/qr/admin/feed`, та же ошибка с другой стороны.
 */
export function formActionPath<T extends string>(path: T): T {
  return withBasePath(path);
}

function withBasePath<T extends string>(path: T): T {
  const base = basePath();
  return (base === "" ? path : `${base}${path}`) as T;
}
