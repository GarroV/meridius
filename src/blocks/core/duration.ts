// Длительность заполнения в виде «3:24» — так она стоит на эталоне ленты и карточки.
// Формат один на все экраны: два разных вида одной величины читаются как две величины.
//
// Откуда взялся этот файл (T256, дефект #124). Форматировщиков было два: один здесь же,
// в ленте, второй — свой, в форме заполнения. Они разошлись в одном знаке: лента
// отбрасывала остаток миллисекунд, квитанция округляла его вверх. Одно и то же
// заполнение показывало «0:02» управляющему и «0:03» сотруднику, который его и сдал.
// Спорить, какое из чисел верное, бессмысленно: дефект не в округлении, а в том, что
// правило жило в двух местах и правка одного не доходила до второго. Сторож от возврата
// второй копии — в `duration.test.ts`: он читает исходники и краснеет, когда рядом
// появляется ещё один `formatDuration`.

const SECOND_MS = 1000;
const MINUTE_S = 60;
const HOUR_S = 3600;

function pad(value: number): string {
  return String(value).padStart(2, "0");
}

/**
 * Длительность строкой «м:сс» — и «ч:мм:сс», когда часы есть.
 *
 * Секунды отбрасываются вниз: 59,9 с — это ещё «0:59», а не «1:00». Часы появляются
 * только когда они есть: «61:00» вместо «1:01:00» читается как секунды. Отрицательного
 * времени не бывает, но часы устройства сотрудника сервером не сверены, поэтому
 * отрицательный вход даёт «0:00», а не «-1:-5».
 *
 * @param durationMs длительность в миллисекундах
 */
export function formatDuration(durationMs: number): string {
  const total = Math.max(0, Math.floor(durationMs / SECOND_MS));
  const seconds = total % MINUTE_S;
  const minutes = Math.floor(total / MINUTE_S) % MINUTE_S;
  const hours = Math.floor(total / HOUR_S);

  if (hours === 0) return `${String(minutes)}:${pad(seconds)}`;
  return `${String(hours)}:${pad(minutes)}:${pad(seconds)}`;
}
