// Ссылка-пропуск меню: первый фокусируемый элемент каждого экрана кабинета.
//
// Зачем. Меню кабинета — это семь пунктов, переключатель темы, переключатель языка и
// кнопка выхода. Без этой ссылки человек с клавиатуры проходит их ВСЕ, чтобы добраться
// до содержимого, и делает это заново на каждой странице. Прогон axe этого не ловил:
// правило `bypass` у него в разряде лучших практик и в наборе не было включено.
//
// Почему подпись берётся здесь, а не приходит пропом от каркаса, и почему тут нет
// `"use client"`. Компонент устроен как соседнее меню (`AdminNav`): без директивы он
// общий, и сторону ему задаёт тот, кто его отрисовал. Это не мелочь оформления, а
// единственный способ обслужить сразу трёх зовущих. Каркас `AdminShell` — серверный,
// и взяв перевод через `getTranslations`, он стал бы асинхронным; но его рисует и
// клиентский `/admin/error.tsx`, а клиентский компонент не может отрисовать
// асинхронный серверный, — то есть сломался бы ровно тот экран, который чинит поломки.
// Редактор же отдаёт наружу ТОЛЬКО свой словарь, поэтому клиентская ссылка осталась бы
// там без подписи. Общий компонент решает все три случая одним видом.
//
// Почему `fixed`, а не привычная пара `sr-only` + `focus:not-sr-only`. Каркас кабинета —
// сетка `208px 1fr` (`admin-frame.ts`), и ссылка лежит прямым ребёнком этой сетки.
// `not-sr-only` возвращает элементу `position: static`, то есть при фокусе ссылка стала
// бы третьей ячейкой сетки и сдвинула макет ровно в тот момент, когда человек на неё
// навёлся. `fixed` не участвует в потоке ни в одном из двух состояний, поэтому макет
// неподвижен, а ссылка при этом остаётся настоящей, а не спрятанной от клавиатуры:
// вне фокуса она уведена за левый край, а не убрана `display: none`.
import { useTranslations } from "next-intl";
import type { ReactElement } from "react";

/** Якорь содержимого. Знают двое: эта ссылка и каркас, который его ставит. */
export const ADMIN_CONTENT_ID = "admin-content";

const CLASS =
  "bg-surface text-ink fixed top-[var(--space-4)] left-[-9999px] z-50 rounded-[var(--r-control)]" +
  " border border-[var(--accent)] px-[var(--space-6)] py-[var(--space-3)]" +
  " text-[length:var(--fs-body)] font-medium no-underline" +
  " focus:left-[var(--space-4)] focus-visible:left-[var(--space-4)]";

export function SkipLink(): ReactElement {
  const t = useTranslations("admin");

  return (
    <a
      href={`#${ADMIN_CONTENT_ID}`}
      data-testid="skip-to-content"
      className={CLASS}
    >
      {t("skipToContent")}
    </a>
  );
}
