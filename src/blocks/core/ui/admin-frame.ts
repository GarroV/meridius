// Сетка каркаса кабинета — одна строка классов на весь продукт (T193, дефект #73).
//
// Почему отдельный файл, а не строка внутри `AdminShell`. Каркас рисуют ДВА места:
// `core/ui/AdminShell.tsx` (пять разделов кабинета) и `editor/ui/EditorScreen.tsx` —
// редактор берёт только меню, потому что его верхняя полоса живёт внутри клиентской
// формы и обязана видеть её состояние. Пока сетка была литералом, эти два места были
// двумя копиями одного решения: ровно тем, чем уже разъезжались меню (T074), шапка
// (T112) и порт приложения (T163, T190, T200). Здесь копия ровно одна.
//
// Что решает сама строка. До `--page-fold` (768 px, `design/reference/tokens.css`)
// меню — боковая колонка 208 px, как в эталоне. Ниже складки колонки нет вовсе:
// один столбец, меню становится верхней полосой (см. `AdminNav`). До этой правки
// 208 px держались на ЛЮБОЙ ширине, и на телефоне 375 px содержимому оставалось
// 167 px — замерено, не на глаз. Отсюда и брались заголовок в три строки, крошки в
// пять и обрезанные значения в списках.
//
// Чего тут сознательно НЕТ. Переработки экранов под телефон: решение владельца D092
// требует «хоть какую-то возможность поправить», а не полноценную работу с телефона.
// Таблицы и сетки разделов остаются со своей прокруткой — её даёт `ADMIN_CONTENT_CLASS`
// ниже, чтобы вбок уезжало содержимое, а не вся страница вместе с заголовком и кнопками.

/**
 * Корень каркаса кабинета: боковая колонка сверху складки, один столбец под ней.
 *
 * Строки заданы явно (`auto 1fr`) — и это не украшение. У сетки `align-content` по
 * умолчанию `stretch`, поэтому на коротком экране свободная высота растягивала ОБЕ
 * строки: полоса меню раздувалась с 53 px до 196-291 px в зависимости от того, сколько
 * содержимого в разделе. Замерено, а не предположено: главная 196, чек-листы 291,
 * QR-коды 279, заполнения (длинный список) 53.
 */
export const ADMIN_FRAME_CLASS =
  "grid min-h-screen grid-cols-[208px_1fr] max-md:grid-cols-[1fr] max-md:grid-rows-[auto_1fr]";

/**
 * Область содержимого. Ниже складки отступы ужимаются (24 → 16 px: на 375 px это 16 px
 * читаемого текста, а не воздуха), а горизонтальная прокрутка достаётся ЕЙ, а не
 * документу. Разница видна сразу: широкая таблица справочника делала документ 926 px
 * при экране 375 px — вбок уезжала вся страница вместе с заголовком и кнопкой, и
 * человек их просто не находил.
 *
 * `relative` ниже складки — не украшение и не запас на будущее, а вторая половина той же
 * починки, найденная разбором. Одной прокрутки не хватило: поля `sr-only` (их ставят ради
 * программ чтения с экрана — в библиотеке блоков и редакторе их несколько) объявлены
 * `position: absolute`, и пока у области содержимого не было позиционирования, их
 * вмещающим блоком оставалась сама страница. Прокрутка их не обрезала: `body` честно
 * показывал 375 px, а документ — 674, и страница уезжала вбок на 299 px ВМЕСТЕ с
 * заголовком. Ловилось это только на разделе с данными, поэтому пустой экран выглядел
 * починенным. С `relative` вмещающий блок — область содержимого, и прокрутка наконец
 * относится и к ним.
 */
export const ADMIN_CONTENT_CLASS =
  "flex flex-col gap-[var(--space-8)] p-[var(--space-9)] max-md:relative max-md:gap-[var(--space-7)] max-md:overflow-x-auto max-md:p-[var(--space-7)]";
