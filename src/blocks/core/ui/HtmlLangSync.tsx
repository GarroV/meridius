"use client";

import { useEffect } from "react";

/**
 * Язык документа равен языку его содержимого (T179).
 *
 * Расхождение, ради которого это заведено: телефон на de-DE открывает станцию страны с
 * `locale=ru`. Экран заполнения показывает русский — так и задумано (язык устройства →
 * язык страны → русский, T038), — а `<html lang>` остаётся `en`: корневая разметка знает
 * только язык запроса, и на неподдержанном языке телефона он откатывается к языку
 * продукта. Синтезатор речи и браузерный перевод верят атрибуту, а не буквам: русская
 * страница, объявленная английской, читается вслух по-английски.
 *
 * Почему поправка здесь, а не на сервере. Решение о языке экрана заполнения зависит от
 * страны пиццерии, то есть от базы, а знать его надо ДО того, как отрисуется `<html>`:
 *   • корневая разметка рендерится раньше страницы — значит, страница не может передать
 *     ей свой язык, ждать его разметка тоже не может (это взаимная блокировка);
 *   • сходить в базу сама разметка не может: `core` — блок, от которого зависят все
 *     остальные, и обратной зависимости на `data`/`fill` у него нет и не будет;
 *   • отдельная корневая разметка для `/s/**` (её Next разрешает через группы маршрутов)
 *     потребовала бы перенести в группы ВСЕ файлы маршрутов, включая чужие блоки, —
 *     переделка такого размера посреди волны ломает работу соседям.
 * Поэтому корень документа догоняет содержимое сразу после гидратации, а сам текст уже
 * объявлен верно и без JavaScript: экран заполнения ставит `lang` на своём корне.
 *
 * Правило узкое нарочно: смотрим ТОЛЬКО на прямого потомка `<body>` — это корень
 * содержимого страницы. `lang` на вложенном элементе (иностранное слово внутри абзаца)
 * говорит про свой кусок текста, а не про документ, и подменять им язык страницы нельзя.
 */
export function HtmlLangSync({
  requestLocale,
}: {
  /** Язык запроса — тот, что проставила корневая разметка. К нему возвращаемся, когда
   * содержимое своего языка не объявляет. */
  readonly requestLocale: string;
}): null {
  useEffect(() => {
    const declared =
      document.body
        .querySelector(":scope > [lang]")
        ?.getAttribute("lang")
        ?.trim() ?? "";
    const wanted = declared === "" ? requestLocale : declared;
    if (document.documentElement.lang !== wanted) {
      document.documentElement.lang = wanted;
    }
  });

  return null;
}
