"use client";

import { useEffect } from "react";

/**
 * Язык документа равен языку его содержимого (T179).
 *
 * Расхождение, ради которого это заведено: телефон на de-DE открывает станцию страны с
 * `locale=ru`. Экран заполнения показывает русский — так и задумано (D122: язык этой
 * поверхности принадлежит пиццерии), — а `<html lang>` оставался `en`, потому что язык
 * документа считался ОТДЕЛЬНО и знал только язык запроса. Синтезатор речи и браузерный
 * перевод верят атрибуту, а не буквам: русская страница, объявленная английской,
 * читается вслух по-английски.
 *
 * ВАЖНОЕ ПРО СЕГОДНЯШНИЙ ДЕНЬ: корень документа больше не врёт и без JavaScript.
 * Расхождение закрыто на сервере (T270) — решение о языке публичного экрана стало одним
 * на запрос (`blocks/fill/document.ts`), и корневая разметка берёт ИМЕННО ЕГО, а не
 * второе умолчание рядом. Проверяется это сквозным сценарием по отданному HTML
 * (`e2e/page-lang.spec.ts`), то есть без гидратации вовсе.
 *
 * Значит, этот компонент из починки стал ЗАПАСНЫМ РУБЕЖОМ: он ничего не исправляет на
 * известных сегодня путях и держится ровно на тот случай, когда язык документа снова
 * разойдётся с содержимым. Стоит он одного `useEffect` без запросов. Снимать его или
 * оставить — решение владельца; пока он стоит, он обязан быть безвредным, поэтому
 * правило ниже узкое и никуда не залезает.
 *
 * Правило узкое нарочно: смотрим ТОЛЬКО на прямого потомка `<body>` — это корень
 * содержимого страницы. `lang` на вложенном элементе (иностранное слово внутри абзаца)
 * говорит про свой кусок текста, а не про документ, и подменять им язык страницы нельзя.
 */
export function HtmlLangSync({
  requestLocale,
}: {
  /** Язык запроса — тот, что проставила корневая разметка. К нему возвращаемся, когда
   * содержимое своего языка не объявляет. */
  readonly requestLocale: string;
}): null {
  useEffect(() => {
    const declared =
      document.body
        .querySelector(":scope > [lang]")
        ?.getAttribute("lang")
        ?.trim() ?? "";
    const wanted = declared === "" ? requestLocale : declared;
    if (document.documentElement.lang !== wanted) {
      document.documentElement.lang = wanted;
    }
  });

  return null;
}
