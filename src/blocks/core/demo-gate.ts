// Ворота демо-режима для маршрутов и действий: «такого адреса нет» вместо экрана.
//
// Отдельно от `demo-mode.ts`: тот читают и скрипты площадки (посев), которым подтягивать
// `next/navigation` незачем.
import { notFound } from "next/navigation";

import { isDemoMode } from "./demo-mode";

/**
 * Закрыть место, которого в демо-режиме быть не должно (учётки, вход, внешние службы).
 * Отвечает «такого адреса нет»: раздел исчез, а не «запрещён» — как партнёру экран УК.
 */
export function hideInDemo(): void {
  if (isDemoMode()) notFound();
}

/** Обратное: место существует только в демо-режиме (`/demo`). Без него — 404, как у любого чужого адреса. */
export function requireDemo(): void {
  if (!isDemoMode()) notFound();
}
