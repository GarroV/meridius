// Разделы кабинета: адрес и готовность — один факт на весь продукт.
//
// До этого модуля каждая боковая навигация (editor, feed, qr, catalog) держала свой список
// адресов и сама решала, какой раздел «ещё не готов». Списки разъехались молча: «Заполнения» и
// «QR-коды» месяц показывались надписью «Раздел ещё не готов», хотя работали, а из справочника
// нельзя было уйти вообще никуда — продукт существовал как набор адресов, а не как целое (#11).
// Границы блоков (`.dependency-cruiser.cjs`) не дают навигации редактора импортировать блок
// заполнений, поэтому общее знание живёт здесь, в `core`, доступном каждому блоку.
//
// Готовность раздела меняется РОВНО здесь. Экран, доводящий раздел до готовности, правит эту
// строку — и все навигации узнают об этом одновременно. Связность проверяет `e2e/admin-nav.spec.ts`.

/** Раздел кабинета: куда ведёт и можно ли туда пускать. */
export interface AdminSection {
  readonly path: string;
  /** `false` — раздела в продукте ещё нет: навигация показывает его неактивным, без ссылки. */
  readonly ready: boolean;
}

export const ADMIN_SECTIONS = {
  checklists: { path: "/admin/checklists", ready: true },
  stations: { path: "/admin/stations", ready: true },
  templates: { path: "/admin/templates", ready: true },
  library: { path: "/admin/library", ready: true },
  feed: { path: "/admin/feed", ready: true },
  catalog: { path: "/admin/catalog", ready: true },
  qr: { path: "/admin/qr", ready: true },
  devices: { path: "/admin/devices", ready: true },
  partners: { path: "/admin/partners", ready: true },
} as const satisfies Record<string, AdminSection>;

/**
 * Главная кабинета. Разделом она не является — в меню её пункта нет и подсвечивать там
 * нечего, — но адрес у неё того же порядка: его знает бренд в меню, входная страница
 * продукта и, отдельной копией, блок входа (`auth/routes.ts`, куда попадает вошедший).
 *
 * Лежит здесь, а не строкой по месту: адреса разделов в этом проекте вычищали трижды
 * (T116, T118, T119) — каждый раз блок держал собственную копию того, что уже лежало тут.
 * Признака готовности у главной нет: она есть всегда, иначе кабинета нет вовсе.
 */
export const ADMIN_HOME: Pick<AdminSection, "path"> = { path: "/admin" };

export type AdminSectionKey = keyof typeof ADMIN_SECTIONS;

/**
 * Разделы, которых в меню больше нет (T312, D163): наклейка и планшет — свойства
 * станции, с ними работают на её карточке. Адреса остались — они уводят в «Станции», а
 * под `/admin/qr` живут экран кода на планшете, его опрос и файл наклейки.
 *
 * Сторож связности меню (`e2e/admin-nav.spec.ts`) их не перебирает: пункта у них нет.
 * Перенаправления держит `e2e/stations-legacy.spec.ts`.
 */
export const ADMIN_REDIRECTED_SECTIONS: readonly AdminSectionKey[] = [
  "qr",
  "devices",
];

/**
 * Разделы только управляющей компании (D169, T337): учётки партнёров ведёт УК. Партнёру
 * адрес отвечает 404, а меню этого пункта не рисует (T344) — ссылка вела бы в 404.
 * Кто вошёл, меню узнаёт от разметки кабинета (`ui/admin-viewer.tsx`).
 */
export const ADMIN_HQ_ONLY_SECTIONS: readonly AdminSectionKey[] = ["partners"];

/**
 * Рабочие пункты меню — то, за чем приходят каждый день (D183, как в Swarm). Главная
 * стоит перед ними всегда и разделом не является (`ADMIN_HOME`), поэтому её здесь нет.
 *
 * Меню делится надвое, а не одним списком (D178 снял подзаголовки групп, D183 вернул
 * деление местом, а не надписью): рабочие пункты — строками рейки, вспомогательные —
 * пиктограммами внизу, как «Настройки» и «Админ» у Swarm. Разделы и адреса при этом
 * не меняются — меняется только место пункта.
 *
 * Лежит рядом с адресами, а не внутри компонента меню: порядок — такой же общий факт,
 * как готовность раздела. Пока меню было четырьмя копиями, разъехались не только списки,
 * но и подписи одного и того же пункта — T074.
 */
export const ADMIN_NAV_WORK = [
  "checklists",
  "stations",
  "feed",
] as const satisfies readonly AdminSectionKey[];

/**
 * Вспомогательные пункты (D183): образцы, кирпичики и опись сети — туда ходят, когда
 * заводят новое, а не каждую смену. Внизу рейки — пиктограммами с подписью при
 * наведении; на телефоне — в листе «Ещё». «Партнёры» видит только УК
 * (`ADMIN_HQ_ONLY_SECTIONS`). «QR-коды» и «Устройства» в меню нет вовсе (T312, D163).
 */
export const ADMIN_NAV_TOOLS = [
  "templates",
  "library",
  "catalog",
  "partners",
] as const satisfies readonly AdminSectionKey[];

/**
 * Табы телефона между «Главной» и «Ещё» (D183, решение Swarm `2026-08-22-mobile-nav`):
 * четыре цели под большой палец, всё остальное — в листе «Ещё». Управляющий с телефона
 * смотрит станции и цифры, чек-листы правят за столом.
 */
export const ADMIN_PHONE_TABS = [
  "stations",
  "feed",
] as const satisfies readonly AdminSectionKey[];

/** Что лежит в листе «Ещё» на телефоне: рабочие пункты мимо табов и вспомогательные. */
export const ADMIN_PHONE_MORE: readonly AdminSectionKey[] = [
  ...ADMIN_NAV_WORK.filter(
    (key) => !(ADMIN_PHONE_TABS as readonly AdminSectionKey[]).includes(key),
  ),
  ...ADMIN_NAV_TOOLS,
];
