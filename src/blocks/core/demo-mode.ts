// Демо-режим продукта (D193): отдельный экземпляр с открытым входом выбором роли.
//
// Здесь, в `core`, а не в блоке `demo`: признак нужен и охране входа (`auth`), и разметке
// кабинета, и словарю языка, а границы модулей (`.dependency-cruiser.cjs`) не дают `auth`
// импортировать `demo`. Лендингу и остальным имя `isDemoMode` отдаёт `src/blocks/demo/mode.ts`.
/** Переменная окружения, включающая демо-режим. Только значение «1»: «true» и «yes» не считаются. */
const DEMO_MODE_ENV = "DEMO_MODE";

/** Адрес выбора роли без базового пути; `redirectPath`/`formActionPath` приставляют его сами. */
export const DEMO_PATH = "/demo";

/** Включён ли демо-режим. Читается на каждый вызов: переменная принадлежит процессу. */
export function isDemoMode(): boolean {
  return process.env[DEMO_MODE_ENV] === "1";
}
