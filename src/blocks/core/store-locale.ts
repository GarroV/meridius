// Язык поверхности, которую читают ЛЮДИ ПИЦЦЕРИИ. Цепочка: язык пиццерии → язык
// устройства → язык продукта.
//
// Чей это язык — решение владельца D122: «дефолт - тот язык что задали для пиццерии.
// отбивки и сервисные сообщения также должны быть на этом языке». То есть поверхность
// принадлежит пиццерии, а не тому, кто её сейчас открыл: чек-лист, отказы,
// предупреждения и служебные надписи идут на языке, который завела пиццерия.
//
// Язык устройства из цепочки не выброшен, но ушёл на вторую роль: интерфейс он больше
// не выбирает, а тексты, заведённые методистом, — да. Пункт мог быть заведён только на
// одном языке; когда на языке пиццерии его нет, показывается тот, что есть, и устройство
// решает, какой из оставшихся ближе человеку.
//
// ПОЧЕМУ ЭТО ЖИВЁТ В `core`, А НЕ В `fill` (T273). Правило написали для публичного
// экрана заполнения, и там оно и лежало. Потом выяснилось, что поверхностей пиццерии
// больше одной: наклейка станции печатается методистом, но висит на кухне и читает её
// сотрудник, — и подпись под кодом уходила на языке БРАУЗЕРА МЕТОДИСТА (замер 20.09,
// стенд 3280: пиццерия со страной `ru` получила имена по-русски, а `scan with a camera`
// по-английски). Блок `qr` до `fill` не дотягивается по графу блоков и не должен: общее
// правило переехало сюда целиком, а не скопировалось вторым экземпляром. Две копии
// правила о языке уже стоили проекту #133 и T268 — там компилятор про копию молчал, и
// здесь молчал бы так же.
//
// Почему не `pickLocale` этого же блока, который уже разбирает `Accept-Language`: он
// отвечает одним языком и на «устройство просит английский», и на «устройство просит
// язык, которого у нас нет». Здесь эти два случая надо различать: во втором устройство
// не сказало ничего, и подставлять за него язык продукта нельзя — он встал бы перед
// языком пиццерии.
import { DEFAULT_LOCALE, isLocale, type Locale } from "./locale";

/**
 * Последнее звено цепочки — язык продукта, а не второе умолчание рядом с ним.
 *
 * Оно срабатывает только там, где пиццерии нет вовсе: код с наклейки не работает,
 * предел частоты сработал раньше похода в базу, пиццерия ещё не выбрана в кабинете.
 * Языка, который «задала пиццерия» (D122), в этом случае не существует, и брать его
 * неоткуда.
 *
 * Раньше здесь стоял русский — «пилот идёт в русскоязычной сети». Этой сети в продукте
 * больше нет: владелец убрал из данных Россию и русскую пиццерию (D083, «у нас весь
 * интерфейс сейчас на инглише»), а второе умолчание давало ровно тот разъезд, о котором
 * заведён #129 — чек-лист и вход по-английски, а «этот код не работает» по-русски, то
 * есть на языке, которого человек с телефоном на третьем языке скорее всего не знает,
 * и ровно в тот миг, когда ему надо понять, что делать дальше.
 *
 * Поэтому значение не написано буквой, а взято из языка продукта: два умолчания в
 * одном продукте разъезжаются молча, одно — не может.
 */
export const STORE_LAST_RESORT_LOCALE: Locale = DEFAULT_LOCALE;

const DEFAULT_QUALITY = 1;

function parseQuality(parameter: string | undefined): number {
  if (parameter === undefined) return DEFAULT_QUALITY;
  const match = /^q=(?<value>[\d.]+)$/.exec(parameter.trim());
  if (match?.groups === undefined) return DEFAULT_QUALITY;
  const value = Number(match.groups["value"]);
  return Number.isFinite(value) ? value : DEFAULT_QUALITY;
}

/** Язык устройства, если продукт на нём говорит. Иначе `null` — не умолчание. */
function deviceLocale(
  acceptLanguage: string | null | undefined,
): Locale | null {
  if (!acceptLanguage) return null;

  const ranked = acceptLanguage
    .split(",")
    .map((entry) => {
      const [tag, ...parameters] = entry.split(";");
      return {
        language: (tag ?? "").trim().toLowerCase().split("-")[0] ?? "",
        quality: parseQuality(parameters[0]),
      };
    })
    .filter((entry) => entry.language !== "" && entry.quality > 0)
    .sort((a, b) => b.quality - a.quality);

  for (const entry of ranked) {
    if (isLocale(entry.language)) return entry.language;
  }
  return null;
}

/**
 * Цепочка языков поверхности по убыванию предпочтения, без повторов и всегда непустая.
 *
 * Первый элемент — язык интерфейса, и это язык пиццерии, когда она известна (D122).
 * Вся цепочка нужна текстам, которые заводит методист: пункт мог быть заведён только на
 * одном языке, и тогда показать надо то, что есть, в том же порядке предпочтения, а не
 * «первое попавшееся из словаря».
 *
 * Ни входа, ни cookie: сотрудник на кухне язык не выбирает (D001). Но и устройство его
 * больше не выбирает — выбрала пиццерия.
 */
export function storeLocales(
  acceptLanguage: string | null | undefined,
  countryLocale: string | null | undefined,
): readonly [Locale, ...Locale[]] {
  const candidates: (Locale | null)[] = [
    isLocale(countryLocale) ? countryLocale : null,
    deviceLocale(acceptLanguage),
  ];

  const preferred: Locale[] = [];
  for (const candidate of candidates) {
    if (candidate !== null && !preferred.includes(candidate)) {
      preferred.push(candidate);
    }
  }

  // Последнее звено — язык продукта, и оно приписывается ЗДЕСЬ, а не стоит третьим
  // кандидатом: так цепочка непустая ПО ТИПУ, а не по обещанию в комментарии. Разница
  // не косметическая — зовущему иначе нужен запасной вариант на случай, которого не
  // бывает, то есть ветка, которую нечем проверить. А непроверяемая ветка однажды
  // оказывается неверной молча: ровно так в этом правиле и жила буква «ru» (#129).
  const [first, ...rest] = preferred;
  if (first === undefined) return [STORE_LAST_RESORT_LOCALE];
  if (preferred.includes(STORE_LAST_RESORT_LOCALE)) return [first, ...rest];
  return [first, ...rest, STORE_LAST_RESORT_LOCALE];
}

/**
 * Язык, на котором поверхность ГОВОРИТ: словарь интерфейса, подписи, отбивки.
 *
 * Это первое звено цепочки, и отдельное имя у него не ради удобства: иначе `[0]`
 * пишется на каждом зовущем экране, а «первый элемент цепочки — это язык интерфейса»
 * становится договорённостью, которую негде проверить. Зовущему с одним экраном (лист
 * печати, наклейка, планшет) вся цепочка не нужна вовсе — у него нет текстов, заведённых
 * методистом по языкам.
 */
export function storeLocale(
  acceptLanguage: string | null | undefined,
  countryLocale: string | null | undefined,
): Locale {
  return storeLocales(acceptLanguage, countryLocale)[0];
}
