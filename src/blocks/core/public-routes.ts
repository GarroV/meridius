// Публичные маршруты продукта — те, что открываются без входа в кабинет.
//
// Здесь, в `core`, потому что знание нужно обеим сторонам, а прямой связи между ними нет:
// политика заголовков (`src/security-headers.ts`) лежит вне границ блоков, а адрес для
// QR-кода строит `qr`, хотя сам маршрут принадлежит `fill`. Границы модулей
// (`.dependency-cruiser.cjs`) не дают `qr` импортировать `fill`, поэтому общий факт живёт
// в `core`, доступном каждому блоку, — ровно как адреса разделов кабинета в
// `core/admin-sections` (#11, T074).
//
// Маршрут переезжает РОВНО здесь. Сторож `public-routes.test.ts` следит, чтобы вторая
// копия не завелась снова: две одинаковые строки дают одинаковый результат до дня переезда,
// а потом расходятся молча (#29, T120).

/** Префикс публичного маршрута заполнения: `/s/<код станции>`. */
export const PUBLIC_FILL_PREFIX = "/s/";

/**
 * Тот же маршрут без кода и без косой черты — `/s`.
 *
 * Считается из префикса, а не пишется второй строкой: две одинаковые строки — та самая
 * копия, которую этот файл и заводился запретить. Адрес понадобился, потому что ссылку
 * обрезают: `/s/` браузер приводит к `/s`, и дальше этот адрес не подходил ни под одну
 * ветку — его забирала охрана кабинета и уводила человека с кухни на пароль админки,
 * которого у него нет и не должно быть (T187).
 */
export const PUBLIC_FILL_ROOT = PUBLIC_FILL_PREFIX.replace(/\/$/, "");

/**
 * Страница привязки планшета: `/pair`. Набирается на планшете один раз в жизни, поэтому
 * адрес короткий и ничего в себе не несёт.
 *
 * Публичная она по той же причине, что и `/s/`: до ввода пина продукт о планшете не знает
 * ничего, а сотруднику с кухни пароль кабинета взять негде (T187, D132).
 */
export const PUBLIC_PAIR_PATH = "/pair";

/**
 * Постоянный адрес привязанной вкладки: `/station`. В адресе нет НИЧЕГО — ни кода
 * станции, ни пиццерии: вкладку закрепляют навсегда, а код станции перевыпускается (D006).
 * Кто пришёл, говорит подписанная кука, а что показать — строка устройства в базе.
 */
export const PUBLIC_STATION_PATH = "/station";
