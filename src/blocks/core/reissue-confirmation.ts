// Правило «перевыпуск кода станции спрашивают, а не делают с одного нажатия» — одно
// на весь продукт (T260, T266).
//
// Почему в `core`, а не по копии в каждом экране. Перевыпуск запускается с ДВУХ
// экранов: из справочника (`catalog/ui/actions.ts`) и с листа печати
// (`qr/ui/actions.ts`). Копия правила разъезжается молча — ровно так в этом проекте
// разъехался форматтер длительности, живший в трёх местах (T256). Здесь цена
// расхождения выше обычной: экран, потерявший вопрос, меняет код станции с одного
// промаха мышью, и все напечатанные наклейки умирают в ту же секунду.
//
// Почему правило стоит ЗДЕСЬ, а не в разметке кнопки. Правило в разметке защищает
// только ту разметку, где о нём вспомнили: прямая отправка формы мимо окна в вебе
// бесплатна и никакой кнопки не касается. Решение действия закрывает оба пути.
//
// Что параметризовано, а что нет. Место, куда экран уходит спрашивать, и место, куда
// он возвращается после отказа, у экранов РАЗНЫЕ (дерево справочника против листа
// печати) — они приходят снаружи. Не параметризована сама развилка: неподтверждённый
// запрос не трогает код НИКОГДА, и переписать это на своём экране нечем.

/** Запрос на перевыпуск: станция, подтверждение и три адреса исходов. */
export interface ReissueRequest<View> {
  readonly stationId: string;
  readonly confirmed: boolean;
  /** Состояние экрана с заданным вопросом: окно подтверждения открыто. */
  readonly ask: View;
  /** Куда уводит удавшийся перевыпуск — на печать новой наклейки. */
  readonly doneHref: string;
  /** Куда вернуть, если перевыпуск не удался: то же место экрана. */
  readonly fail: View;
}

/**
 * Что делать с запросом: сперва спросить или уже перевыпускать и вести на печать.
 *
 * Обе ветки несут с собой ВСЁ, что понадобится действию. Собирать это в самом
 * действии значило бы держать половину решения в файле с `"use server"`, где его
 * нечем проверить тестом: такой файл экспортирует только асинхронные функции.
 */
export type ReissueDecision<View> =
  | { readonly kind: "confirm"; readonly view: View }
  | {
      readonly kind: "reissue";
      readonly stationId: string;
      readonly doneHref: string;
      readonly failView: View;
    };

/**
 * Перевыпуск в два шага: подтверждение, потом сам перевыпуск.
 *
 * Тот же порядок, что у удаления станции (`submitDeleteStation`): неподтверждённый
 * запрос ничего не меняет, а уводит экран в состояние подтверждения.
 *
 * После подтверждения экран не возвращается туда, откуда пришёл, а открывает печать
 * новой наклейки: обещание кнопки — «перевыпустить И открыть печать», и без второго
 * шага методист уходит со старой наклейкой на станции и новым кодом в базе.
 */
export function decideReissue<View>(
  request: ReissueRequest<View>,
): ReissueDecision<View> {
  const { stationId, confirmed, ask, doneHref, fail } = request;

  if (!confirmed) {
    return { kind: "confirm", view: ask };
  }

  return { kind: "reissue", stationId, doneHref, failView: fail };
}
