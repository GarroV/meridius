// Проверка окружения площадки при старте продукта. Зовётся из `src/instrumentation.ts`.
//
// Смысл ровно один: настройка, из-за которой продукт работает неправильно, обязана
// останавливать его при старте, а не всплывать через неделю на экране у методиста
// или молча выключать защиту. Значения переменных запекаются в сборку (D033),
// поэтому «поднялся — значит настроен» здесь дорогого стоит.
import {
  TRUSTED_PROXY_HOPS_VAR,
  trustedProxyHops,
} from "@/blocks/fill/rate-limit";
import { publicBasePath } from "@/blocks/qr/sticker-origin";
import { configuredOrigin } from "@/blocks/qr/ui/origin";

/**
 * Проверяет окружение и возвращает то, о чём стоит сказать вслух.
 *
 * Отказ (исключение) — там, где значение задано и негодно. Пустое окружение
 * отказом не считается: свежий клон и сквозные сценарии поднимаются без `.env`.
 */
export function checkStartupConfig(
  env: Record<string, string | undefined>,
): readonly string[] {
  const notes: string[] = [];

  // Бросает, если адрес задан и негоден: иначе первая же наклейка печатается в никуда.
  configuredOrigin(env);

  // То же про базовый путь площадки: он уезжает внутрь напечатанного кода вместе
  // с адресом, поэтому негодное значение останавливает продукт здесь (D045).
  const basePath = publicBasePath(env);
  if (basePath !== "") {
    notes.push(
      `BASE_PATH задан (${basePath}). Переходы между экранами кабинета префикс получают: ` +
        "они идут через Link, и путь приставляет сам Next (T088). Мимо роутера остались " +
        "два места, и им префикс НЕ приставляется — скачивание наклейки (<a download> на " +
        "/admin/qr/sticker) и опрос кода планшетом (fetch на /admin/qr/code). Обычные " +
        "GET-формы фильтров (лента, список чек-листов) тоже идут мимо роутера, и префикс " +
        "им приставляет formActionPath() — без него выбор страны уводил на страницу " +
        "«такой страницы нет» (проверено на стенде 24.09.2026). Публикация идёт отдельным " +
        "туннелем на корне адреса (D046), то есть путь включать незачем",
    );
  }

  // Бросает, если число посредников задано и негодно.
  if (trustedProxyHops(env) === 0) {
    notes.push(
      `${TRUSTED_PROXY_HOPS_VAR} не задан: предел на открытие экрана заполнения по клиенту НЕ применяется — ` +
        "заголовку о клиенте без объявленного посредника доверять нечем. " +
        "Отправка заполнений при этом ограничена по-прежнему: по коду станции и по сети целиком",
    );
  }

  // Вход в админку: без этих двух переменных ни один экран /admin не открывается,
  // а падает это только в момент нажатия кнопки — ошибкой сервера, по которой
  // неотличимо, продукт сломан или окружение не заполнено (куплено 07.09.2026:
  // `.env` скопировали из примера и оставили значения пустыми).
  const missingLogin = (["SESSION_SECRET", "ADMIN_PASSWORD_HASH"] as const)
    .filter((name) => (env[name] ?? "").trim() === "")
    .join(" и ");
  if (missingLogin !== "") {
    notes.push(
      `вход в админку не настроен: не задано ${missingLogin}. ` +
        "Продукт поднимется, но /admin ответит ошибкой при попытке войти. См. .env.example",
    );
  }

  // Привязка планшета: без секрета подписи страница `/pair` отказывает на вводе кода,
  // а привязанная вкладка просит код заново — то есть выглядит это как отвязка, которой
  // никто не делал. Говорим об этом при старте, а не в тот момент, когда человек с кухни
  // стоит у планшета.
  if ((env["DEVICE_SESSION_SECRET"] ?? "").trim() === "") {
    notes.push(
      "привязка планшета не настроена: не задан DEVICE_SESSION_SECRET. Продукт поднимется, " +
        "но /pair откажет на вводе кода, а привязанные планшеты попросят новый. См. .env.example",
    );
  }

  return notes;
}
