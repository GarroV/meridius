import { pingDatabase } from "@/blocks/data";

/**
 * Проверка здоровья для контейнера и обратного прокси.
 *
 * Отвечает 200, только когда продукт может сделать свою работу: процесс поднят И база
 * отвечает. Один процесс без базы — это экран с ошибкой на каждом запросе, и называть
 * его здоровым значит пустить на него трафик. Главная для этого не годится: она рисует
 * страницу, а падение базы на ней выглядит как 500 без объяснения причины.
 *
 * В ответе нет ни коммита, ни текста ошибки: адрес открыт без входа, и рассказывать
 * наружу, что именно сломалось, незачем. Причина уходит в журнал сервера.
 */
export const dynamic = "force-dynamic";

export async function GET(): Promise<Response> {
  try {
    await pingDatabase();
  } catch (cause) {
    console.error("healthz: база не отвечает", cause);
    return Response.json({ status: "unavailable" }, { status: 503 });
  }
  return Response.json({ status: "ok" });
}
