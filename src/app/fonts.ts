// Шрифты продукта в одном месте: их подключает корневая разметка и ОБЯЗАН подключать
// последний рубеж (`global-error.tsx`), потому что он заменяет разметку целиком.
//
// Появилось из T264. Классы `next/font` жили прямо в `layout.tsx`, и на последнем рубеже
// их не было вовсе: переменная `--font-ui-loaded` не объявлялась, `--font-ui` откатывался
// к запасному списку, и экран набирался системным шрифтом. Заметить это по коду нельзя —
// он выглядит одинаково, — а на экране это другой продукт.
import { Golos_Text, IBM_Plex_Mono } from "next/font/google";

/**
 * Шрифты эталона (`docs/furca/design/screens/*.html` грузят их из Google Fonts).
 * Здесь их подключает `next/font`: файлы скачиваются один раз на сборке и раздаются
 * с адреса самого приложения. На кухне это и есть разница между «экран открылся» и
 * «экран ждёт чужой домен» на слабой связи; заодно ни один запрос не уходит на сторону.
 *
 * Имя семейства `next/font` придумывает своё, поэтому оно попадает в CSS-переменную,
 * а не подменяет токен: список запасных шрифтов остаётся в `tokens.css` (D013).
 */
const golosText = Golos_Text({
  subsets: ["latin", "cyrillic"],
  // Токены просят 400/500/600/700 — переменное начертание отдаёт их одним файлом.
  weight: "variable",
  display: "swap",
  variable: "--font-ui-loaded",
});

const plexMono = IBM_Plex_Mono({
  subsets: ["latin", "cyrillic"],
  // Эталон грузит ровно эти два: моноширинным набраны время, коды станций и числа.
  weight: ["400", "500"],
  display: "swap",
  // Без предзагрузки (T248). Начертаний четыре — два веса на два алфавита, — и
  // предзагружались все четыре, тогда как странице нужен один: браузер печатал
  // предупреждение о неиспользуемой предзагрузке на каждом экране продукта, а
  // канал первого кадра уходил на файлы, которые не нужны. Моноширинным набраны
  // время, коды и числа — не первый кадр, и `display: swap` дожидается файла,
  // показывая запасное начертание. Предзагрузка остаётся у основного шрифта
  // интерфейса: им набран весь текст первого экрана.
  preload: false,
  variable: "--font-num-loaded",
});

/** Классы с переменными шрифтов — на `<html>`, где бы эта разметка ни строилась. */
export const FONT_VARIABLES = `${golosText.variable} ${plexMono.variable}`;
